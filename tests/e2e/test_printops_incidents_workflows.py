"""`3d printops incidents` end to end: bin/3d → real uvicorn 3d-api → FakeMoonraker (U1) and
FakeSpoolman over HTTP (#165). The user syncs print exposure from the printer's job history,
reports a clog with nothing but printer + head (3d-api fills job, layer, G-code temperatures and
the spool's lot), lets a watch event draft a second incident, confirms it, and reads the rates
per kg / print-hour by lot."""

