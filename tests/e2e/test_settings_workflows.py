def test_the_legacy_buffer_moves_imports_once_and_the_gate_sees_the_calibrations(
    tmp_path: Path, live_api: LiveApi
) -> None:
    """The K1 SE was calibrated by hand (orange PLA PA 0.05, flow 0.931, MVS 22) and the changes sit
    in the pre-#264 buffer. The user dry-runs the import, imports it binding the black PLA line to
    its spool, imports again (nothing added), and the calibration gate passes a G-code sliced with
    those values instead of failing on "no record"."""
    orange = add_spool(live_api.spoolman, "PLA оранжевый", ORANGE, slot="k1se/T1")
    black = add_spool(live_api.spoolman, "чёрный PLA", BLACK, slot="u1/T1")
    legacy = tmp_path / "xdg-data" / "3d" / "printer-history"
    legacy.mkdir(parents=True)
    entries = buffer(orange)
    entries[4]["note"] = (
        "readout\u2028second paragraph"  # literal U+2028 inside a JSON string
    )
    text = "\n".join(lines(entries)) + "\n"
    assert "\u2028" in text
    (legacy / "k1se.jsonl").write_text(text, encoding="utf-8")
    moved = tmp_path / "xdg-data" / "3d-cli" / "printer-history" / "k1se.jsonl"
    env = {"PRINTOPS_API": live_api.url, "PRINTOPS_TOKEN": live_api.tokens["rw"]}

    dry = run_cli(tmp_path, "settings", "import", "--dry-run", env_extra=env)
    assert dry.returncode == 1, (
        dry.stdout + dry.stderr
    )  # the black PLA and method-less shaper lines
    assert (
        f"DRY RUN (rolled back) {moved}: 10 lines — 8 imported (4 calibration records), 0 skipped, 2 refused"
        in dry.stdout
    )
    assert (
        "pass --spool u-black-pa=<spool id>" in dry.stdout
        and "2 line(s) refused" in dry.stderr
    )
    assert (
        "pass --method u-shaper=<klipper_shaper_calibrate|k1_auto|u1_auto>"
        in dry.stdout
    )
    assert (
        not legacy.exists() and moved.read_text(encoding="utf-8") == text
    )  # moved, never rewritten

    done = run_cli(
        tmp_path,
        "settings",
        "import",
        "--spool",
        f"u-black-pa={black}",
        "--method",
        "u-shaper=klipper_shaper_calibrate",
        env_extra=env,
    )
    assert done.returncode == 0, done.stdout + done.stderr
    assert (
        "10 lines — 10 imported (6 calibration records), 0 skipped, 0 refused"
        in done.stdout
    )
    assert "pressure_advance=0.05" in done.stdout and f"spool #{orange}" in done.stdout

    again = run_cli(tmp_path, "settings", "import", str(moved), env_extra=env)
    assert again.returncode == 0, again.stdout + again.stderr
    assert (
        "10 lines — 0 imported (0 calibration records), 10 skipped, 0 refused"
        in again.stdout
    )

    plan = run_cli(
        tmp_path, "calibrate", "plan", "--printer", "k1se", "--all", env_extra=env
    )
    assert plan.returncode == 0, plan.stderr
    rows = {ln.split()[2]: ln for ln in plan.stdout.splitlines() if ln.startswith("  ")}
    for kind in (
        "pressure_advance",
        "flow_ratio",
        "max_volumetric_speed",
        "input_shaper",
    ):
        assert " current " in rows[kind], plan.stdout

    gcode = tmp_path / "orange.gcode"
    gcode.write_text(
        "; generated by Snapmaker Orca (test)\nG28\nT0\nG1 X10 Y10 E1 F1200\n"
        '; filament_settings_id = "Orange PLA @K1SE"\n; filament_type = PLA\n'
        "; filament_flow_ratio = 0.931\n; enable_pressure_advance = 1\n; pressure_advance = 0.05\n"
        "; filament_max_volumetric_speed = 20\n; printer_model = Creality K1 SE\n",
        encoding="utf-8",
    )
    check = run_cli(
        tmp_path, "calibrate", "check", str(gcode), "--printer", "k1se", env_extra=env
    )
    assert check.returncode == 0, check.stdout + check.stderr
    for kind in ("pressure_advance", "flow_ratio"):
        line = next(ln for ln in check.stdout.splitlines() if f" {kind} " in ln)
        assert line.split()[0] == "PASS" and "current" in line, check.stdout

    hist = run_cli(
        tmp_path,
        "settings",
        "history",
        "--printer",
        "k1se",
        "--kind",
        "pressure_advance",
        env_extra=env,
    )
    assert hist.returncode == 0, hist.stderr
    assert len(hist.stdout.splitlines()) == 2
    assert (
        '{"pressure_advance": 0.05}' in hist.stdout
        and "user_visual_choice" in hist.stdout
    )


def test_a_repeated_spool_option_is_refused(tmp_path: Path) -> None:
    """The user binds two refused lines by repeating --spool, as each refusal hint suggests; the
    parser would keep only the last one, so the command stops and shows the comma-separated form
    instead of silently dropping a binding."""
    res = run_cli(tmp_path, "settings", "import", "--spool", "a=1", "--spool", "b=2",
                  env_extra={"PRINTOPS_API": "http://127.0.0.1:9", "PRINTOPS_TOKEN": "x"})
    assert res.returncode == 2
    assert "--spool given 2 times" in res.stderr and "--spool UID=…,UID=…" in res.stderr
