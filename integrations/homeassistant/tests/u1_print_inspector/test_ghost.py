def _box_gcode(layers: int = 6) -> bytes:
    out = [
        "; generated by Snapmaker Orca 2.3.5",
        "M83",
        f"SET_PRINT_STATS_INFO TOTAL_LAYER={layers} CURRENT_LAYER=0",
    ]
    for n in range(1, layers + 1):
        out += [
            ";LAYER_CHANGE",
            f";Z:{n * 0.5:g}",
            f"SET_PRINT_STATS_INFO CURRENT_LAYER={n}",
            "T1",
            "G1 X100 Y40 F9000",
            ";TYPE:Outer wall",
            "G1 X140 Y40 E1",
            "G1 X140 Y80 E1",
            "G1 X100 Y80 E1",
            "G1 X100 Y40 E1",
            ";TYPE:Sparse infill",
            "G1 X120 Y60 E1",
        ]
    out += ["; filament_colour = #1B5E20;#FFFFFF"]
    return ("\n".join(out) + "\n").encode()


class Recorder:
    def __init__(self):
        self.comments: list[str] = []
        self.moves: list[tuple] = []

    def comment(self, text):
        self.comments.append(text)

    def move(self, *args):
        self.moves.append(args)


def test_index_pass_feeds_the_shell_collector():
    rec = Recorder()
    GCodeIndex.parse(io.BytesIO(_box_gcode(2)), shell=rec)
    assert "filament_colour = #1B5E20;#FFFFFF" in rec.comments
    walls = [m for m in rec.moves if m[3] == "outer wall"]
    assert len(walls) == 8  # four sides on each of two layers
    assert walls[0] == (1, 0.5, 1, "outer wall", 140.0, 40.0, True, None)
    assert walls[-1][:3] == (2, 1.0, 1)
    travel = [m for m in rec.moves if not m[6]]
    assert travel and travel[0][4:6] == (100.0, 40.0)


def test_shell_gets_absolute_mm_through_g91_g20_g92_and_arcs():
    gcode = b"""M83
;LAYER_CHANGE
;Z:0.2
SET_PRINT_STATS_INFO CURRENT_LAYER=1
G1 X100 Y100 F6000
;TYPE:Outer wall
G91
G1 X10 Y0 E1
G90
G20
G1 X5 Y4 E1
G21
G92 X0 Y0
G1 X-10 Y-10 E1
G3 X-10 Y-10 I5 J0 E3
"""
    rec = Recorder()
    index = GCodeIndex.parse(io.BytesIO(gcode), shell=rec)
    walls = [m for m in rec.moves if m[6]]
    assert [m[4:6] for m in walls] == [
        (110.0, 100.0),
        (127.0, 101.6),
        (117.0, 91.6),
        (117.0, 91.6),
    ]
    assert walls[0][7] is None and walls[-1][7] == (
        5.0,
        0.0,
        False,
    )  # G3: counter-clockwise
    assert index.layers[1].extrusion_mm == pytest.approx(
        30.4
    )  # E bookkeeping: 1 + 1 in + 1 + 3


class Exploding(Recorder):
    def move(self, *args):
        raise FloatingPointError("bad wall")


def test_a_failing_wall_collector_never_breaks_the_index():
    reports = []
    shell = u1_ghost.IsolatedShell(Exploding(), reports.append)
    index = GCodeIndex.parse(io.BytesIO(_box_gcode(2)), shell=shell)
    assert len(index.layers) == 2  # the index completed
    assert shell.finish() is None
    assert reports == ["FloatingPointError: wall collection failed: bad wall"]


def test_real_shell_collects_walls_only():
    builder = u1_ghost.GhostRenderer(enabled=True).new_builder()
    assert builder is not None, (
        "3d-cli lib/vision_ghost must be importable next to the scripts"
    )
    GCodeIndex.parse(io.BytesIO(_box_gcode()), shell=builder)
    shell = builder.finish()
    assert shell.colours == ("#1B5E20", "#FFFFFF")
    assert len(shell.layer) == 6 and sorted(shell.layer_z) == [1, 2, 3, 4, 5, 6]
    assert set(shell.tool.tolist()) == {1}


def _status(data: bytes, index, layer=3, **kw):
    pos = data.index(f"CURRENT_LAYER={layer}".encode())
    st = {
        "print_stats": {
            "state": "printing",
            "filename": "box.gcode",
            "info": {"current_layer": layer, "total_layer": 6},
        },
        "virtual_sdcard": {"file_size": index.size, "file_position": pos},
        "toolhead": {"extruder": "extruder1"},
        "extruder1": {"extruder_index": 1},
    }
    st.update(kw)
    return st


def _inspector_with(data: bytes):
    insp = Inspector("http://127.0.0.1:9")
    builder = u1_ghost.GhostRenderer(enabled=True).new_builder()
    index = GCodeIndex.parse(io.BytesIO(data), shell=builder)
    insp.index, insp.shell, insp.index_state = index, builder.finish(), "ready"
    return insp, index


def test_ghost_source_only_for_the_running_indexed_job():
    data = _box_gcode()
    insp, index = _inspector_with(data)
    snap = enrich(_status(data, index), index, index_state="ready")
    job, shell, layer = insp.ghost_source(snap)
    assert job == index.sha256 and shell is insp.shell and layer == 3
    assert insp.ghost_source({**snap, "stale": True}) == (None, None, None)
    assert insp.ghost_source({**snap, "job_fingerprint": "0" * 64}) == (
        None,
        None,
        None,
    )
    assert insp.ghost_source({**snap, "state": "complete"}) == (None, None, None)
    other = enrich(
        _status(
            data,
            index,
            virtual_sdcard={"file_size": index.size + 1, "file_position": 10},
        ),
        index,
        index_state="ready",
    )
    assert insp.ghost_source(other) == (None, None, None)  # a different file is running


def _jpeg(w=320, h=180) -> bytes:
    from PIL import Image

    buf = io.BytesIO()
    Image.new("RGB", (w, h), (40, 40, 40)).save(buf, format="JPEG", quality=95)
    return buf.getvalue()


class _FakeGhost:
    def __init__(self, shape):
        import numpy as np

        self.shape = shape
        self.index = np.arange(0, 320 * 20)  # top 20 rows
        self.inv_alpha = np.full((len(self.index), 1), 128, np.uint16)
        self.premult = np.full((len(self.index), 3), 255 * 128, np.uint16)

    def blend(self, rgb):
        flat = rgb.reshape(-1, 3)
        flat[self.index] = (
            (flat[self.index].astype("uint16") * self.inv_alpha + self.premult) >> 8
        ).astype("uint8")
        return rgb


def test_overlay_blends_a_ghost_and_is_unchanged_without_one():
    from PIL import Image

    data = _box_gcode()
    _, index = _inspector_with(data)
    snap = enrich(_status(data, index), index, index_state="ready")
    plain = overlay(_jpeg(), snap)
    assert overlay(_jpeg(), snap, ghost=lambda shape: None) == plain
    seen = []
    with_ghost = overlay(
        _jpeg(), snap, ghost=lambda shape: seen.append(shape) or _FakeGhost(shape)
    )
    assert seen == [(180, 320)]
    top = Image.open(io.BytesIO(with_ghost)).convert("RGB").getpixel((160, 5))
    assert top[0] > 120  # 40 -> ~148 under a white half-alpha ghost


def _wait_for(pred, timeout=30.0):
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        if pred():
            return True
        time.sleep(0.05)
    return False


def test_renderer_renders_once_per_layer_in_the_background(monkeypatch):
    data = _box_gcode(8)
    insp, index = _inspector_with(data)
    calls = []
    real = u1_ghost._modules()[1].render

    def counting(*args, **kwargs):
        calls.append(args[2])
        return real(*args, **kwargs)

    monkeypatch.setattr(u1_ghost._modules()[1], "render", counting)
    r = u1_ghost.GhostRenderer(enabled=True)
    shape = (1080, 1920)
    assert (
        r.ghost_for(index.sha256, insp.shell, 3, shape) is None
    )  # scheduled, not ready
    assert _wait_for(lambda: r.pending is None and r.cache is not None)
    g = r.ghost_for(index.sha256, insp.shell, 3, shape)
    assert g is not None and len(g.index) > 0  # the box is in the U1 camera's view
    assert r.ghost_for(index.sha256, insp.shell, 3, shape) is g
    assert calls == [3]
    # the next layer (0.5 mm up) shows the layer-3 ghost while its own renders...
    assert r.ghost_for(index.sha256, insp.shell, 4, shape) is g
    assert _wait_for(lambda: r.pending is None and r.cache[0][1] == 4)
    assert calls == [3, 4]
    # ...also exactly MAX_LAG_MM (1 mm) behind, but never further behind, nor another job's
    lagging = r.cache[1]
    assert lagging is not None
    assert r.ghost_for(index.sha256, insp.shell, 6, shape) is lagging  # 2.0 -> 3.0 mm
    assert _wait_for(lambda: r.pending is None and r.cache[0][1] == 6)
    r.cache = ((index.sha256, 4, shape), lagging)  # pretend layer 4 is the last render
    assert r.ghost_for(index.sha256, insp.shell, 7, shape) is None  # 2.0 -> 3.5 mm
    assert _wait_for(lambda: r.pending is None and r.cache[0][1] == 7)
    assert r.ghost_for("f" * 64, insp.shell, 7, shape) is None
    r.set_enabled(False)
    assert r.ghost_for(index.sha256, insp.shell, 7, shape) is None
    assert r.ghost_for(None, insp.shell, 7, shape) is None


def test_render_failure_is_reported_and_not_retried(monkeypatch):
    def boom(*_args, **_kwargs):
        raise RuntimeError("x")

    monkeypatch.setattr(u1_ghost._modules()[1], "render", boom)
    r = u1_ghost.GhostRenderer(enabled=True)
    r.ghost_for("job", object(), 2, (10, 10))
    assert _wait_for(lambda: r.cache is not None)
    assert r.state()["error"] == "RuntimeError: ghost render failed: x"
    assert r.state()["layer"] == 2 and r.state()["layer_has_ghost"] is False
    assert r.ghost_for("job", object(), 2, (10, 10)) is None and r.pending is None


def test_post_ghost_switches_and_get_reports():
    import u1_mjpeg_proxy as proxy

    server = ThreadingHTTPServer(("127.0.0.1", 0), proxy.Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    base = f"http://127.0.0.1:{server.server_address[1]}"
    try:

        def post(body: bytes):
            req = urllib.request.Request(
                base + "/ghost",
                data=body,
                method="POST",
                headers={"Content-Type": "application/json"},
            )
            try:
                with urllib.request.urlopen(req, timeout=5) as resp:
                    return resp.status, json.loads(resp.read())
            except urllib.error.HTTPError as err:
                return err.code, json.loads(err.read())

        assert post(b'{"enabled": false}') == (
            200,
            {**proxy.ghosts.state(), "enabled": False},
        )
        with urllib.request.urlopen(base + "/ghost", timeout=5) as resp:
            assert json.loads(resp.read())["enabled"] is False
        assert post(b'{"enabled": "yes"}')[0] == 400
        assert post(b"not json")[0] == 400
        assert post(b"x" * 2000)[0] == 400  # over the 1 KiB body limit
        assert post(b'{"enabled": true}')[1]["enabled"] is True
    finally:
        server.shutdown()
        proxy.ghosts.set_enabled(True)
