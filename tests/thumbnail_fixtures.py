"""Fixtures for the thumbnail layers: a G-code with no thumbnails, with some, and with all of them.

The G-code is what the Orca CLI writes: a header, a few extruding layers, a config block that names
`; thumbnails = 48x48/PNG, 96x96/PNG, 300x300/PNG`. `bare` has no block, `partial` only the 48x48 one,
`complete` all three."""

from __future__ import annotations

import re
import zipfile
from pathlib import Path

import numpy as np

import gcode_thumbnails as gt

SPEC = "48x48/PNG, 96x96/PNG, 300x300/PNG"
ALL_SIZES = [(48, 48), (96, 96), (300, 300)]
HEADER = (
    "; HEADER_BLOCK_START\n; generated by Snapmaker Orca 2.4.0\n; HEADER_BLOCK_END\n\n"
)
BODY = "G90\nM83\nT0\n;TYPE:Outer wall\n" + "".join(
    f"G1 Z{z}\nG1 X10 Y10\nG1 X40 Y10 E1\nG1 X40 Y25 E1\nG1 X10 Y25 E1\nG1 X10 Y10 E1\n"
    for z in (0.2, 0.4, 0.6)
)
CONFIG = "; CONFIG_BLOCK_START\n; filament_colour = #C12E1F\n; thumbnails = {spec}\n; CONFIG_BLOCK_END\n"
MACROS_ONLY = "G28\nM104 S0\nTEMPERATURE_WAIT SENSOR=extruder MAXIMUM=38\n"


def bare(path: Path, spec: str | None = SPEC, body: str = BODY) -> Path:
    config = (
        CONFIG.format(spec=spec)
        if spec
        else CONFIG.replace("; thumbnails = {spec}\n", "")
    )
    path.write_text(HEADER + body + config, encoding="ascii")
    return path


def partial(path: Path) -> Path:
    """Only the 48x48 block, drawn from a flat colour so its bytes differ from what ensure() would draw."""
    bare(path)
    tile = np.full((48, 48, 4), 200, np.uint8)
    gt.splice(str(path), gt.block(gt.Thumb(48, 48, "PNG"), gt.encode_png(tile)))
    return path


def complete(path: Path) -> Path:
    bare(path)
    gt.ensure(str(path))
    return path


def block_sizes(path: Path) -> list[tuple[int, int]]:
    """(w, h) of every thumbnail block in the file, in order (duplicates included)."""
    return [
        (int(w), int(h))
        for w, h in re.findall(
            r"; thumbnail begin (\d+)x(\d+) \d+", path.read_text(encoding="ascii")
        )
    ]


def plate_project(path: Path, *, members: dict[str, bytes] | None = None) -> Path:
    """A minimal Orca project 3MF with settings but no plate pictures (what the headless CLI exports)."""
    base = {
        "[Content_Types].xml": b'<?xml version="1.0"?><Types xmlns="x"><Default Extension="rels" ContentType="r"/></Types>',
        "_rels/.rels": b'<?xml version="1.0"?><Relationships xmlns="x"></Relationships>',
        "3D/3dmodel.model": b"<model/>",
        "Metadata/project_settings.config": b'{"layer_height": "0.2"}',
    }
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in {**base, **(members or {})}.items():
            z.writestr(name, data)
    return path
