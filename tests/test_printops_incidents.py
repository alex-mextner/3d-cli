def _kinds(conn: sqlite3.Connection) -> list[str]:
    return [r["kind"] for r in conn.execute("SELECT kind FROM events WHERE kind LIKE 'incident.%' ORDER BY id")]


def test_report_validation_and_aliases() -> None:
    r = Report.from_dict({"kind": "Layer split", "severity": "print_lost", "nozzle_temp": 215, "tags": ["petg"]})
    assert r.kind == "delamination" and r.given == {"nozzle_temp": 215.0}
    for bad, msg in (({"kind": "melted", "severity": "cosmetic"}, "unknown incident kind"),
                     ({"kind": "clog", "severity": "meh"}, "unknown severity"),
                     ({"kind": "clog", "severity": "cosmetic", "layer": 2.5}, "layer must be an integer"),
                     ({"kind": "clog", "severity": "cosmetic", "room_rh": 140}, "0..100"),
                     ({"kind": "clog", "severity": "cosmetic", "colour": "red"}, "unknown field")):
        with pytest.raises(IncidentError, match=msg):
            Report.from_dict(bad)


def test_lifecycle_draft_confirm_resolve_and_dismiss(printops_db: sqlite3.Connection) -> None:
    conn = printops_db
    draft = incidents.create(conn, Report("other", "part_lost", reported_by="watch", status="draft",
                                          source_key="watch:k1"), actor="t", auto={"printer": "u1", "layer": 7})
    with pytest.raises(IncidentError, match="confirm or dismiss it first"):
        incidents.resolve(conn, draft.id, "dried", actor="t")
    with pytest.raises(IncidentError) as dup:
        incidents.create(conn, Report("other", "part_lost", source_key="watch:k1"), actor="t")
    assert dup.value.status == 409
    ok = incidents.confirm(conn, draft.id, {"kind": "clog", "add_tags": ["ptfe"]}, actor="alex")
    assert (ok.status, ok.kind, ok.tags, ok.layer) == ("open", "clog", ["ptfe"], 7)
    done = incidents.resolve(conn, draft.id, "cleaned_nozzle", actor="alex", text="cold pull")
    assert done.status == "resolved" and done.resolution_kind == "cleaned_nozzle" and done.resolved_at
    with pytest.raises(IncidentError, match="already resolved"):
        incidents.resolve(conn, draft.id, "none", actor="alex")
    other = incidents.create(conn, Report("stringing", "cosmetic"), actor="t")
    gone = incidents.dismiss(conn, other.id, actor="alex", reason="duplicate of #1")
    assert gone.status == "dismissed" and "[dismissed] duplicate of #1" in (gone.note or "")
    edited = incidents.update(conn, done.id, {"add_photos": ["https://ha/x.jpg"], "room_rh": 55}, actor="alex")
    assert edited.photos == ["https://ha/x.jpg"] and edited.room_rh == 55
    assert _kinds(conn) == ["incident.created", "incident.confirmed", "incident.resolved", "incident.created",
                            "incident.dismissed", "incident.updated"]


