"""Synthetic sliced plates for the overhang tests (lib/gcode_overhangs.py).

Each layer of an object is a solid zigzag fill of rectangles at 0.45 mm line spacing and
width, as a slicer's solid infill looks. Real plates are covered by the regression tests on
the babushkin-dom K1 SE G-codes."""

from __future__ import annotations

from pathlib import Path

Rect = tuple[float, float, float, float]  # x0, y0, x1, y1
WIDTH = 0.45
LAYER = 0.2


def fill(rect: Rect) -> list[str]:
    x0, y0, x1, y1 = rect
    out = [f"G1 X{x0:.3f} Y{y0:.3f} F9000"]
    y, forward = y0, True
    while y <= y1 + 1e-9:
        out.append(f"G1 X{(x1 if forward else x0):.3f} Y{y:.3f} E0.05")
        y += WIDTH
        if y <= y1 + 1e-9:
            out.append(f"G1 X{(x1 if forward else x0):.3f} Y{y:.3f} E0.01")
        forward = not forward
    return out


def plate(path: Path, objects: dict[str, list[list[Rect]]]) -> Path:
    """objects[name][i] = the rectangles that object prints on layer i (z = 0.2 + i * 0.2).
    A purge line in the start G-code, before the first layer marker, is not the plate."""
    out = ["; generated by synthetic fixture", "G28", "G90", "M83"]
    out += [f"EXCLUDE_OBJECT_DEFINE NAME={name}" for name in objects]
    out += ["G1 Z0.3 F600", "G1 X0 Y-3 F9000", "G1 X60 Y-3 E5"]
    for i in range(max(len(v) for v in objects.values())):
        z = round(LAYER + i * LAYER, 3)
        out += [";LAYER_CHANGE", f";Z:{z:g}", f"G1 Z{z:g}"]
        for name, per_layer in objects.items():
            out.append(f"EXCLUDE_OBJECT_START NAME={name}")
            if i < len(per_layer) and per_layer[i]:
                out += [";TYPE:Internal solid infill", f";WIDTH:{WIDTH}"]
                for rect in per_layer[i]:
                    out += fill(rect)
            out.append(f"EXCLUDE_OBJECT_END NAME={name}")
    out += [
        "; CONFIG_BLOCK_START",
        f"; initial_layer_print_height = {LAYER:g}",
        f"; layer_height = {LAYER:g}",
        f"; line_width = {WIDTH}",
    ]
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path


SQUARE: Rect = (10.0, 10.0, 30.0, 30.0)


def floating(n: int = 6) -> list[list[Rect]]:
    """A bottom that is not flat: only four 2 x 2 mm corner bumps touch the bed, the 20 x 20 mm
    slab above them prints in the air (the K1 overlay)."""
    bumps = [(10.0, 10.0, 12.0, 12.0), (28.0, 10.0, 30.0, 12.0), (10.0, 28.0, 12.0, 30.0), (28.0, 28.0, 30.0, 30.0)]
    return [bumps] + [[SQUARE] for _ in range(n - 1)]


def step_out(n: int = 6, by: float = 1.0) -> list[list[Rect]]:
    """A box whose upper half is `by` mm wider on one side: an edge one line or two wider."""
    x0, y0, x1, y1 = SQUARE
    return [[SQUARE] for _ in range(n // 2)] + [[(x0, y0, x1 + by, y1)] for _ in range(n - n // 2)]


def bridge(n: int = 6, gap: float = 10.0) -> list[list[Rect]]:
    """Two 5 mm walls `gap` mm apart, then a slab across them: a bridge between walls."""
    left = (10.0, 10.0, 15.0, 30.0)
    right = (15.0 + gap, 10.0, 20.0 + gap, 30.0)
    return [[left, right] for _ in range(n - 1)] + [[(10.0, 10.0, 20.0 + gap, 30.0)]]


def tip(n: int = 6) -> list[list[Rect]]:
    """A box with a blob 3 mm off its top edge, ~1 mm2 as drawn (0.6 mm square plus the line
    width): a grass-blade tip, below --min-area."""
    return [[SQUARE] for _ in range(n - 1)] + [[SQUARE, (33.0, 20.0, 33.6, 20.6)]]
