"""proof.py — the proof pack of a `3d prep` run: renders, heat-maps, diagrams and one markdown report.

WHAT: `build(pipe)` reads the step records and meshes of a finished pipeline and writes `proof-report.md` plus
  `proof/*.png` into the work dir: model views, before/after of the adaptation, overhang heat-map, a section,
  the fit matrix with a lean pose, the stability plan, region colours, the layer-height plan and the renders of
  the sliced G-code, each section with its verdict and key numbers, ending in the honest limits.
WHY: in the Chekhov session the proofs were ~12 hand-written Blender/matplotlib scripts, re-run per edit, and a
  nested lock hung one of them for 25 minutes. Here every picture is produced from the cached results.
INVARIANTS: only `prep.raster` / `prep.panels` / `prep.report` draw (pure numpy, no Blender/GL); a section is
  written for every step that ran, SKIPs included with their reason; the pack never edits a step result.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING, Any

import numpy as np
import trimesh

from prep import frame, panels, raster
from prep.contracts import Verdict
from prep.pipeline import STEPS, StepOutput
from prep.report import REPORT_NAME, ProofReport

if TYPE_CHECKING:
    from prep.pipeline import Pipeline

VIEWS: tuple[str, ...] = ("front", "left", "back", "top", "iso", "low")
SIZE = (560, 560)

LIMITS = (
    "Mass and centre of mass come from a voxel model (perimeter shell at 100 %, the rest at the chosen infill, PLA 1.24 g/cm3); the slicer's own mass replaces it once sliced.",
    "Friction figures are the coefficient a pose NEEDS (a linear-program equilibrium on the contact clusters); nothing here measured the real PLA-on-glass/silicone friction.",
    "Overhang analysis is a voxel model at the chosen pitch (one layer per cell); the slicer's own support spots and the G-code overhang gate are the final word.",
    "Colour mixes are layer stripes judged by the stripe-average model; the printed colour is not measured and the filaments' real hues differ from their listed hex.",
    "The proof renders are numpy point-splats of the mesh: good for shape and regions, not for surface quality.",
)


def _rows(pairs: Sequence[tuple[str, Any]]) -> list[tuple[str, str]]:
    return [(k, str(v)) for k, v in pairs if v is not None]


def _hex_rgb(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def build(pipe: Pipeline) -> StepOutput:
    cfg = pipe.cfg
    report = ProofReport()
    for line in LIMITS:
        report.add_limit(line)
    final = pipe.final_mesh()
    images_dir = pipe.work / "proof"
    images_dir.mkdir(exist_ok=True)

    for name in STEPS:
        if name == "proof":
            continue
        rec = pipe.records.get(name)
        if rec is None:
            continue
        images: list[Any] = []
        rows: list[tuple[str, str]] = []
        notes: list[str] = []
        if rec.verdict != "SKIP":
            images, rows, notes = _section_content(pipe, name, rec.result, final)
        verdict, summary = rec.verdict, rec.summary
        repair = pipe.records.get("repair")
        if (
            name == "diagnose"
            and verdict == "FAIL"
            and repair is not None
            and repair.verdict in ("PASS", "WARN")
        ):
            # defects the next step repaired are a finding, not a failed print
            verdict, summary = "WARN", f"repaired by the next step: {summary}"
        report.add_section(
            name,
            verdict,
            summary,
            rows,
            images,
            notes,
            seconds=rec.seconds if not rec.cached else rec.original_seconds,
        )
    meta = {
        "model": cfg.model.name,
        "digest (sha256 prefix)": frame.file_digest(cfg.model),
        "printer": cfg.printer,
        "process": f"{cfg.walls} walls, {cfg.infill_pct}% infill, layers {cfg.hmin:g}-{cfg.hmax:g} mm",
    }
    report_path = report.write(
        pipe.work,
        title=f"Prep proof: {cfg.model.name}",
        subtitle="Generated by `3d prep`; every number below comes from the step results in prep.json.",
        meta=meta,
    )
    n_png = len(list((pipe.work / "proof").glob("*.png")))
    # the pack's own verdict is "was it produced"; the worst step verdict is in the report header and prep.json
    return StepOutput(
        {"report": report_path.name, "images": n_png, "overall": report.overall},
        "PASS",
        f"{report_path.name} with {n_png} images (overall {report.overall})",
        [report_path],
    )


def _section_content(
    pipe: Pipeline, name: str, data: dict[str, Any], final: trimesh.Trimesh
) -> tuple[list[Any], list[tuple[str, str]], list[str]]:
    fn = _SECTIONS.get(name)
    if fn is None:
        return [], [], []
    return fn(pipe, data, final)


Content = tuple[list[Any], list[tuple[str, str]], list[str]]


def _diagnose(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    keys = (
        "faces",
        "components",
        "watertight",
        "boundary_edges",
        "nonmanifold_edges",
        "nonmanifold_vertices",
        "debris_shells",
        "volume_mm3",
    )
    return [], _rows([(k, d.get(k)) for k in keys]), list(d.get("defects", []))


def _repair(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    after = d.get("after", {})
    rows = _rows(
        [
            ("backend", d.get("backend")),
            ("max deviation mm", d.get("max_deviation_mm")),
            ("watertight after", after.get("watertight")),
            ("faces after", after.get("faces")),
        ]
    )
    return [], rows, list(d.get("actions", []))


def _orient(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    rows = _rows(
        [
            ("applied", d.get("applied")),
            ("chosen", d.get("chosen")),
            ("evaluated", d.get("evaluated")),
        ]
    )
    for c in d.get("candidates", [])[:5]:
        rows.append(
            (
                f"#{c['rank']} {c['label']}",
                f"overhang {c['overhang_area_mm2']:.0f} mm2, contact {c['contact_area_mm2']:.0f} mm2, height {c['height_mm']:.1f} mm, score {c['score']:.3f}",
            )
        )
    return [], rows, list(d.get("reasons", []))


def _adapt(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    rows = [
        (
            f"{o['op']}",
            f"+{o['added_volume_mm3']:.0f} mm3 / -{o['removed_volume_mm3']:.0f} mm3, {o['faces']} faces, watertight={o['watertight']}",
        )
        for o in d.get("ops", [])
    ]
    if not d.get("ops"):
        return [], rows, []
    before_mesh = pipe.mesh_after("orient")
    return (
        [panels.before_after(before_mesh, final, views=("iso", "low"), size=SIZE)],
        rows,
        [o.get("reason", "") for o in d["ops"] if o.get("reason")],
    )


def _overhang(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    cfg = pipe.cfg
    imgs = panels.overhang_heatmap(
        final, angle_deg=cfg.angle_deg, views=("low", "iso", "bottom"), size=SIZE
    )
    sheet = panels.contact_sheet(
        imgs,
        ["underside", "iso", "bottom"],
        3,
        f"Overhang vs {cfg.angle_deg:g} deg, final model",
    )
    rows = _rows(
        [
            ("islands", d.get("island_count")),
            ("regions", d.get("region_count")),
            ("total area mm2", d.get("total_area_mm2")),
            ("max span mm", d.get("max_span_mm")),
        ]
    )
    for r in d.get("regions", [])[:5]:
        rows.append(
            (
                f"region z {r['z_mm'][0]:.1f}-{r['z_mm'][1]:.1f}",
                f"{r['area_mm2']:.1f} mm2, span {r['span_mm']:.1f} mm",
            )
        )
    views = [raster.render_mesh(final, view=v, size=SIZE) for v in VIEWS]
    model_sheet = panels.contact_sheet(
        views, list(VIEWS), 3, f"{cfg.model.name}: final model"
    )
    section = raster.render_section(
        final, (0.0, 0.0, final.bounds[1][2] / 2), (1.0, 0.0, 0.0), SIZE
    )
    return [model_sheet, sheet, section], rows, list(d.get("reasons", []))


def _fit(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    items, cases, matrix = d["items"], d["cases"], d["matrix"]
    verdicts = [[matrix[i].get(c, "SKIP") for c in cases] for i in items]
    rows = _rows([("counts", d.get("counts")), ("mode", d.get("mode"))])
    images: list[Any] = [panels.verdict_matrix(items, cases, verdicts)]
    posed = [
        r
        for r in d["rows"]
        if not r["non_goal"]
        and r["verdict"] in ("PASS", "RISK")
        and r.get("phi_deg") is not None
    ]
    if posed:
        r = max(posed, key=lambda row: row["mass_g"])
        pose = {
            "y0": r["y0_mm"],
            "z0": r["z0_mm"],
            "phi_deg": r["phi_deg"],
            "thickness": r["thick_mm"],
            "height": r["height_mm"],
            "width": r["width_mm"],
        }
        images.append(panels.profile_with_slab(final, pose))
        rows.append(
            (
                "pose drawn",
                f"{r['item']} / {r['case']} ({r['mass_g']:.0f} g), lean {r['phi_deg']:.0f} deg, needs mu {r['mu_req']}",
            )
        )
    return images, rows, list(d.get("reasons", []))


def _stability(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    scenarios = d.get("scenarios", [])
    loaded = scenarios[-1] if len(scenarios) > 1 else None
    img = panels.stability_diagram(
        np.asarray(d["support_polygon_mm"], dtype=np.float64),
        d["com_mm"][:2],
        loaded["com_mm"][:2] if loaded else None,
        loaded["min_margin_mm"] if loaded else None,
    )
    rows = _rows(
        [
            ("mass g", d.get("mass_g")),
            ("CoM mm", [round(v, 1) for v in d["com_mm"]]),
            ("support area mm2", d.get("support_area_mm2")),
        ]
    )
    for s in scenarios:
        rows.append(
            (
                s["name"],
                f"tip angle {s['tip_angle_deg']:.1f} deg, margin {s['min_margin_mm']:.1f} mm, {s['verdict']}",
            )
        )
    return [img], rows, list(d.get("reasons", []))


def _colors(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    from prep import regions

    cfg = pipe.cfg
    if cfg.colors is None:
        return [], [], []
    spec = regions.load_colour_spec(cfg.colors, mix_cap=cfg.mix_cap)
    lab = regions.label_faces(final, spec)
    fil = {f.key: f for f in spec.filaments}
    by_slot = {str(f.slot): f for f in spec.filaments}
    palette: dict[int, tuple[int, int, int]] = {}
    for i, region in enumerate(spec.regions):
        a = region.assign
        if a.mix:  # a mix reads as the average of its components (the stripe-average model of the colour rules)
            parts = [
                _hex_rgb((fil.get(c) or by_slot[c]).hex)
                for c in a.mix
                if c in fil or c in by_slot
            ]
            if parts:
                n = len(parts)
                palette[i] = (
                    sum(p[0] for p in parts) // n,
                    sum(p[1] for p in parts) // n,
                    sum(p[2] for p in parts) // n,
                )
            continue
        f = fil.get(a.key) if a.key else by_slot.get(str(a.slot))
        if f is not None:
            palette[i] = _hex_rgb(f.hex)
    names = dict(enumerate(lab.names))
    imgs = panels.region_map(
        final, lab.labels, palette, names, views=("iso", "back", "top"), size=SIZE
    )
    rows = [
        (
            p["name"],
            f"{p['assign']}, {p['volume_mm3']:.0f} mm3, z {p['z_range'][0]:.1f}-{p['z_range'][1]:.1f}",
        )
        for p in d.get("parts", [])
    ]
    return (
        [panels.contact_sheet(imgs, ["iso", "back", "top"], 3, "Colour regions")],
        rows,
        list(d.get("reasons", [])),
    )


def _layers(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    img = panels.layer_band_plot(
        d["z_tops"],
        d["heights"],
        mix_ranges=[tuple(r) for r in d.get("mix_zranges", [])],
    )
    s = d.get("stats", {})
    rows = _rows(
        [
            ("layers", d.get("layers")),
            ("at hmin %", s.get("at_hmin_pct")),
            ("median mm", s.get("median")),
            ("top error mm", d.get("top_error")),
            ("first layer mm", d.get("first_height")),
        ]
    )
    mix = d.get("mix_check")
    if mix:
        rows.append(
            (
                "mix rules",
                f"{len(mix.get('violations', []))} violation(s) in {mix.get('checked')} checked pattern(s), engine {mix.get('engine')}",
            )
        )
    return [img], rows, list(d.get("reasons", []))


def _project(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    rows = _rows(
        [
            ("3MF", d.get("project")),
            ("prime tower", d.get("prime_tower")),
            ("tower xy", d.get("tower_xy")),
            ("parts", len(d.get("parts", [])) or None),
        ]
    )
    return [], rows, []


def _slice(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    rows = _rows(
        [
            ("G-code", d.get("gcode")),
            ("slicer seconds", d.get("seconds")),
            ("warnings", len(d.get("warnings", []))),
        ]
    )
    notes = [str(w.get("message", w)) for w in d.get("warnings", [])][:10]
    return [], rows, notes


def _gates(pipe: Pipeline, d: dict[str, Any], final: trimesh.Trimesh) -> Content:
    from prep import gcode_gates, gcode_view

    cfg = pipe.cfg
    rows = [(g["name"], f"{g['verdict']}: {g['detail']}") for g in d.get("gates", [])]
    images: list[Any] = []
    gcode = pipe.work / f"{cfg.name}.gcode"
    if gcode.is_file():
        parsed = gcode_gates.parse(gcode)
        colours = _tool_colours(pipe)
        paths = gcode_view.render_layers(
            parsed, pipe.work / "proof" / "gcode", colours=colours
        )
        images.extend(paths)
        hist = gcode_view.layer_histogram(parsed)
        images.append(
            panels.layer_band_plot(
                hist["z"],
                hist["h"],
                mix_ranges=[
                    tuple(r)
                    for r in (pipe.record_data("layers").get("mix_zranges") or [])
                ],
            )
        )
    return images, rows, []


def _tool_colours(pipe: Pipeline) -> dict[int, str]:
    """Tool number -> hex: slot n is tool Tn-1."""
    from prep import regions
    from prep.pipeline import default_filaments

    cfg = pipe.cfg
    fils = (
        list(regions.load_colour_spec(cfg.colors, mix_cap=cfg.mix_cap).filaments)
        if cfg.colors
        else default_filaments()
    )
    return {f.slot - 1: f.hex for f in fils}


_SECTIONS = {
    "diagnose": _diagnose,
    "repair": _repair,
    "orient": _orient,
    "adapt": _adapt,
    "overhang": _overhang,
    "fit": _fit,
    "stability": _stability,
    "colors": _colors,
    "layers": _layers,
    "project": _project,
    "slice": _slice,
    "gates": _gates,
}


def verdict_of(rec_verdict: Verdict) -> Verdict:
    """Identity kept for symmetry with report sections; the proof never rewrites a step verdict."""
    return rec_verdict


__all__ = ["REPORT_NAME", "build"]
