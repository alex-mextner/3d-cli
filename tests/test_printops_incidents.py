def test_two_events_of_one_failure_at_once_make_one_draft(
    fleet: Path, sm: FakeSpoolman, printops_db: sqlite3.Connection, printops_settings: Settings,
    monkeypatch: pytest.MonkeyPatch
) -> None:
    real = watch_incidents.resolve
    both_resolving = threading.Barrier(2, timeout=10)

    def slow(*args: Any, **kw: Any) -> Any:
        both_resolving.wait()  # neither has created its draft yet
        return real(*args, **kw)

    monkeypatch.setattr(watch_incidents, "resolve", slow)
    rd, _ = readers_for(u1_status("printing", "plate.gcode", 0.3), ())
    events = [watch_event("stall", "warning", key="u1:stall:1"),
              watch_event("filament", key="u1:filament:2", sensor="filament_switch_sensor e2")]
    outs: list[watch_incidents.Outcome] = []

    def deliver(event: dict[str, Any]) -> None:
        conn = open_db(printops_settings.db_path)  # 3d-api: one connection per request
        try:
            outs.append(watch_incidents.draft_from_watch(conn, sm, event, readers=rd, actor="watch"))
        finally:
            conn.close()

    threads = [threading.Thread(target=deliver, args=(e,)) for e in events]
    for t in threads:
        t.start()
    for t in threads:
        t.join(30)
    assert sorted((o.created, o.merged) for o in outs) == [(False, True), (True, False)]
    assert printops_db.execute("SELECT COUNT(*) FROM incident").fetchone()[0] == 1


def test_watch_draft_bounds_the_gcode_scan_below_the_exec_sink_timeout(
    fleet: Path, sm: FakeSpoolman, printops_db: sqlite3.Connection, monkeypatch: pytest.MonkeyPatch
) -> None:
    from printer_ops.watch_sinks import ExecSink

    ends: list[float | None] = []
    downloads: list[object] = []
    real = watch_incidents.resolve

    def spy(*args: Any, readers: Readers, **kw: Any) -> Any:
        ends.append(readers.deadline_at)
        downloads.append(readers.download)
        return real(*args, readers=readers, **kw)

    monkeypatch.setattr(watch_incidents, "resolve", spy)
    rd, _ = readers_for(u1_status("printing", "plate.gcode", 0.3), ())
    rd.download = lambda *_a, **_k: Path("/x")  # PRINTOPS_GCODE_FETCH=1 on this 3d-api
    exec_timeout = ExecSink("true").timeout
    assert rd.deadline_s > exec_timeout  # the interactive report keeps its longer budget
    before = time.monotonic()
    out = watch_incidents.draft_from_watch(printops_db, sm, watch_event("stall", "warning"), readers=rd, actor="watch")
    after = time.monotonic()
    (end,) = ends
    budget = watch_incidents.WATCH_DEADLINE_S
    # the scan ends a fixed budget after the request arrived, printer reads included
    assert out.created and budget < exec_timeout and end is not None and before + budget <= end <= after + budget
    assert downloads == [None]  # a watch draft never pulls the G-code off the printer


