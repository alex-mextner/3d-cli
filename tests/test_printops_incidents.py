def test_state_at_resumes_from_layer_checkpoints_with_the_same_answer(tmp_path: Path) -> None:
    text = orca_gcode(layers=6)
    g = tmp_path / "plate.gcode"
    g.write_text(text)
    queries: list[dict[str, int]] = [{"layer": 5}, {"layer": 2}, {"byte": byte_of(text, "G1 X30 Y30 E0.6", nth=4) + 1},
                                     {"layer": 6}, {"byte": 3}]
    gcode_resume._CHECKPOINTS.clear()
    warm = [state_at(g, **q) for q in queries]  # every scan after the first resumes from a checkpoint
    (marks,) = gcode_resume._CHECKPOINTS.values()
    assert len(marks) == 6
    cold = []
    for q in queries:
        gcode_resume._CHECKPOINTS.clear()
        cold.append(state_at(g, **q))
    assert warm == cold


def test_state_at_checkpoints_keep_a_mid_print_temperature_change_out_of_earlier_layers(tmp_path: Path) -> None:
    text = orca_gcode(layers=6)
    cut = byte_of(text, ";AFTER_LAYER_CHANGE", nth=4)  # ASCII: byte offset == str index
    g = tmp_path / "plate.gcode"
    g.write_text(text[:cut] + "M104 S230 T2\nM141 S50\n" + text[cut:])
    gcode_resume._CHECKPOINTS.clear()
    state_at(g, layer=6)  # checkpoints every layer, the later ones after the change
    warm = state_at(g, layer=2)
    gcode_resume._CHECKPOINTS.clear()
    cold = state_at(g, layer=2)
    assert warm == cold and (warm.state["temp"][2], warm.state["chamber"]) == (220.0, 40.0)


def test_state_at_checkpoints_stay_within_the_per_file_budget(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    text = orca_gcode(layers=6)
    g = tmp_path / "plate.gcode"
    g.write_text(text)
    gcode_resume._CHECKPOINTS.clear()
    full = state_at(g, layer=6)
    size = gcode_resume._state_entries(full.state)
    monkeypatch.setattr(gcode_resume, "_CHECKPOINT_ENTRIES_PER_FILE", 3 * size)
    gcode_resume._CHECKPOINTS.clear()
    capped = state_at(g, layer=6)
    (marks,) = gcode_resume._CHECKPOINTS.values()
    stored = sum(gcode_resume._state_entries(m.state) for m in marks.values())
    assert 3 <= len(marks) < 6 and stored <= 3 * size
    assert capped == full and state_at(g, layer=6) == full  # past the budget: resumes from the last one


