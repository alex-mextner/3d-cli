def orca_gcode(layers: int = 4) -> str:
    """A small Snapmaker-Orca-shaped plate: head T2 (tool 2) prints walls and infill per layer."""
    out = ["; HEADER_BLOCK_START", "; generated by Snapmaker Orca 2.4.0", "; HEADER_BLOCK_END",
           "; EXECUTABLE_BLOCK_START", "M140 S65", "M104 S215 T0", "M104 S220 T2", "M141 S40",
           "M106 S0", "M83", "T2", "G1 E5 F300"]
    for n in range(1, layers + 1):
        z = round(n * 0.2, 2)
        out += [";LAYER_CHANGE", f";Z:{z}", ";HEIGHT:0.2", ";AFTER_LAYER_CHANGE", f"G1 Z{z} F600",
                f"M106 S{0 if n == 1 else 204}",
                ";TYPE:Outer wall", ";WIDTH:0.42", "G1 X10 Y10 F12000", "G1 F3000", "G1 X20 Y10 E0.5", "G1 X20 Y20 E0.5",
                ";TYPE:Sparse infill", ";WIDTH:0.45", "G1 F6000", "G1 X30 Y20 E0.6", "G1 X30 Y30 E0.6",
                "G1 E-0.8 F1800"]
    out += ["; EXECUTABLE_BLOCK_END", ""]
    return "\n".join(out)


def byte_of(text: str, needle: str, nth: int = 1) -> int:
    pos = -1
    for _ in range(nth):
        pos = text.index(needle, pos + 1)
    return len(text[:pos].encode())


