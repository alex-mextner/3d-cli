def test_lint_flags_stale_drafts_and_open_hardware_risks(sm: FakeSpoolman, printops_db: sqlite3.Connection) -> None:
    conn = printops_db
    old = (datetime.datetime.now(UTC) - datetime.timedelta(days=10)).isoformat()
    stale = incidents.create(conn, Report("clog", "part_lost", status="draft", at=old), actor="t", auto={"printer": "u1"})
    risky = incidents.create(conn, Report("heat_creep", "hardware_risk", at=old), actor="t", auto={"printer": "k1se"})
    incidents.create(conn, Report("clog", "hardware_risk"), actor="t")  # fresh: fine
    found = datalint.run(datalint.LintContext(conn, sm, [], datetime.datetime.now(UTC)))
    mine = sorted((f.rule, f.subject) for f in found if f.rule.startswith("incidents/"))
    assert mine == [("incidents/draft-stale", f"incident:{stale.id}"),
                    ("incidents/hardware-risk-open", f"incident:{risky.id}")]
    assert json.dumps([f.as_dict() for f in found])  # serialisable for GET /v1/lint
