def plate_gcode() -> str:
    out = ["; generated by Snapmaker Orca 2.4.0", "; EXECUTABLE_BLOCK_START", "M140 S65", "M104 S215 T2", "M83", "T2"]
    for n in range(1, 6):
        out += [";LAYER_CHANGE", f";Z:{n * 0.2:.1f}", ";HEIGHT:0.2", ";AFTER_LAYER_CHANGE", "M106 S255",
                ";TYPE:Outer wall", ";WIDTH:0.42", "G1 F2400", "G1 X10 Y10 E0.4", "G1 X20 Y10 E0.4"]
    return "\n".join([*out, "; EXECUTABLE_BLOCK_END", ""])


@pytest.fixture
def u1(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[tuple[FakeMoonraker, str]]:
    gdir = tmp_path / "gcodes"
    gdir.mkdir()
    text = plate_gcode()
    (gdir / "plate.gcode").write_text(text)
    remote = f"plate-{hashlib.sha256(text.encode()).hexdigest()[:16]}.gcode"
    moon = FakeMoonraker()
    with moon.serve():
        st = u1_status("printing", remote, 0.6)
        st["print_stats"]["info"] = {"current_layer": 4, "total_layer": 5}
        st["virtual_sdcard"]["file_size"] = len(text.encode())
        moon.status = st
        monkeypatch.setenv("THREED_FLEET", str(write_fleet(tmp_path / "fleet.yaml", u1_entry(moon))))
        monkeypatch.setenv("PRINTOPS_GCODE_DIRS", str(gdir))
        monkeypatch.delenv("PRINTOPS_GCODE_FETCH", raising=False)
        yield moon, remote


@pytest.fixture
def live(tmp_path: Path, u1: tuple[FakeMoonraker, str]) -> Iterator[LiveApi]:
    with serve_api(tmp_path, FakeSpoolman()) as api:
        yield api


def _env(live: LiveApi, token: str = "rw") -> dict[str, str]:
    return {"PRINTOPS_API": live.url, "PRINTOPS_TOKEN": live.tokens[token]}


def _load_spool(live: LiveApi, lot: str) -> int:
    sp = live.spoolman
    vendor = sp.create("vendor", {"name": "Elegoo"})
    fil = sp.create("filament", {"name": "RAPID PLA+ Green", "vendor_id": vendor["id"], "material": "PLA+",
                                 "density": 1.24, "diameter": 1.75, "weight": 1000})
    sid = int(sp.create("spool", {"filament_id": fil["id"], "lot_nr": lot})["id"])
    ApiClient(live.url, live.tokens["rw"]).post("/v1/printers/u1/slots/T3/load", {"spool_id": sid})
    return sid


def _from_watch(tmp_path: Path, live: LiveApi, event: dict[str, Any]) -> subprocess.CompletedProcess[str]:
    """What `3d printer watch u1 --exec '3d printops incidents from-watch'` runs per event."""
    env = {**isolated_env(tmp_path), **_env(live)}
    return subprocess.run([sys.executable, str(THREED), "printops", "incidents", "from-watch"], input=json.dumps(event),
                          env=env, capture_output=True, text=True, timeout=120, cwd=tmp_path)


def test_sync_report_watch_draft_confirm_and_rates_by_lot(
    tmp_path: Path, live: LiveApi, u1: tuple[FakeMoonraker, str]
) -> None:
    moon, remote = u1
    sid = _load_spool(live, "L2409")
    after_load = datetime.datetime.now(datetime.timezone.utc).timestamp() + 1
    moon.history = [
        {"job_id": "00005B", "filename": remote, "status": "in_progress", "start_time": after_load + 7200},
        {"job_id": "00005A", "filename": "walls.gcode", "status": "completed", "start_time": after_load,
         "end_time": after_load + 7200, "print_duration": 7200.0, "filament_used": 3000.0,
         "metadata": {"filament_weight": [0, 0, 400.0, 0], "filament_total": 3000.0}},
    ]
    env = _env(live)

    synced = run_cli(tmp_path, "printops", "incidents", "exposure", "sync", "u1", env_extra=env)
    reported = run_cli(tmp_path, "printops", "incidents", "report", "clog", "--severity", "print_lost",
                       "--printer", "u1", "--head", "T3", "--tag", "ptfe", env_extra=env)
    watched = _from_watch(tmp_path, live, {
        "ts": datetime.datetime.now().astimezone().isoformat(timespec="seconds"), "printer": "u1",
        "kind": "filament", "severity": "critical", "text": "u1: filament runout on e2", "key": "u1:filament:7",
        "data": {"state": "printing", "file": remote, "layer": 4, "sensor": "filament_switch_sensor e2"}})
    drafts = run_cli(tmp_path, "printops", "incidents", "ls", "--status", "draft", "--json", env_extra=env)
    draft_id = json.loads(drafts.stdout)["incidents"][0]["id"]
    confirmed = run_cli(tmp_path, "printops", "incidents", "confirm", str(draft_id), "--kind", "tangle",
                        env_extra=env)
    shown = run_cli(tmp_path, "printops", "incidents", "show", "1", env_extra=env)
    stats = run_cli(tmp_path, "printops", "incidents", "stats", "--by", "lot", env_extra=env)
    stats_json = run_cli(tmp_path, "printops", "incidents", "stats", "--by", "lot", "--json", env_extra=env)

    assert synced.returncode == 0, synced.stderr
    assert "u1: 2 job(s) read, 1 exposure row(s) added, 0 already synced, 1 still printing" in synced.stdout
    assert f"job 00005A T3: 2.00 h, 400 g spool #{sid}" in synced.stdout
    assert reported.returncode == 0, reported.stderr
    assert re.search(rf"recorded #1 \[open\] .* clog \(print_lost\)  u1/T3  spool #{sid} Elegoo PLA\+ RAPID PLA\+ Green "
                     r"lot L2409", reported.stdout), reported.stdout
    assert f"job {remote} (00005B), layer 4 z 0.8, outer wall, nozzle 215 °C, bed 65 °C" in reported.stdout
    assert "speed 40 mm/s" in reported.stdout and "fan 100 %" in reported.stdout
    assert watched.returncode == 0, watched.stderr
    assert watched.stdout.startswith("draft runout (print_lost, confidence 0.8): #2 [draft]")
    assert confirmed.returncode == 0 and "confirmed #2 [open]" in confirmed.stdout and "tangle" in confirmed.stdout
    assert "layer             ← u1 status: current layer" in shown.stdout
    assert "SHA-256" in shown.stdout and "tags ptfe" in shown.stdout
    assert stats.returncode == 0, stats.stderr
    assert re.search(r"5\.000/kg\s+1\.0000/h\s+2 in\s+0\.4 kg /\s+2\.0 h  lot L2409 · Elegoo PLA\+ RAPID PLA\+ Green",
                     stats.stdout), stats.stdout
    assert "[clog 1, tangle 1]" in stats.stdout
    group = json.loads(stats_json.stdout)["groups"][0]
    assert (group["per_kg"], group["per_hour"], group["parent"]["label"]) == (5.0, 1.0, "Elegoo")
    gets = {r.path for r in moon.requests}
    assert not moon.writes() and gets <= {"/printer/objects/query", "/server/history/list"}  # read-only


def test_manual_exposure_resolve_dismiss_and_errors(tmp_path: Path, live: LiveApi) -> None:
    env = _env(live)
    added = run_cli(tmp_path, "printops", "incidents", "exposure", "add", "p1s", "--hours", "3.5", "--grams", "120",
                    env_extra=env)
    listed = run_cli(tmp_path, "printops", "incidents", "exposure", "ls", env_extra=env)
    one = run_cli(tmp_path, "printops", "incidents", "report", "warping", "--severity", "part_lost", "--printer",
                  "p1s", "--set", "room_rh=61", "--no-context", env_extra=env)
    resolved = run_cli(tmp_path, "printops", "incidents", "resolve", "1", "glue", "--text", "glue stick", env_extra=env)
    two = run_cli(tmp_path, "printops", "incidents", "report", "stringing", "--severity", "cosmetic", env_extra=env)
    dismissed = run_cli(tmp_path, "printops", "incidents", "dismiss", "2", "--reason", "test", env_extra=env)
    no_sev = run_cli(tmp_path, "printops", "incidents", "report", "clog", env_extra=env)
    bad_kind = run_cli(tmp_path, "printops", "incidents", "report", "melted", "--severity", "cosmetic", env_extra=env)
    read_only = run_cli(tmp_path, "printops", "incidents", "report", "clog", "--severity", "cosmetic",
                        env_extra=_env(live, "read"))
    offline_sync = run_cli(tmp_path, "printops", "incidents", "exposure", "sync", "p1s", env_extra=env)

    assert added.returncode == 0, added.stderr
    assert "p1s/T1       3.50 h      120 g  [manual]" in added.stdout
    assert "total: 1 row(s), 3.5 h, 0.12 kg" in listed.stdout
    assert one.returncode == 0 and "room RH 61 %" in one.stdout
    assert resolved.returncode == 0 and "resolved" in resolved.stdout and "glue_plate — glue stick" in resolved.stdout
    assert two.returncode == 0 and dismissed.returncode == 0 and "dismissed #2 [dismissed]" in dismissed.stdout
    assert no_sev.returncode == 2 and "--severity is required" in no_sev.stderr
    assert bad_kind.returncode == 1 and "unknown incident kind 'melted'" in bad_kind.stderr
    assert read_only.returncode == 1 and "HTTP 403" in read_only.stderr
    assert offline_sync.returncode == 1 and "offline fleet printer" in offline_sync.stderr


def test_help_and_docs_stay_in_sync(tmp_path: Path) -> None:
    helped = run_cli(tmp_path, "printops", "incidents", "--help")
    assert helped.returncode == 0 and helped.stdout.strip() == USAGE.strip()
    doc = (ROOT / "docs" / "commands" / "printops-incidents.md").read_text(encoding="utf-8")
    for line in USAGE.splitlines():
        if line.startswith("3d printops incidents "):
            assert line.split(" [")[0] in doc, f"{line!r} missing from docs/commands/printops-incidents.md"
    assert "printops incidents" in (ROOT / "docs" / "commands" / "printops.md").read_text(encoding="utf-8")
