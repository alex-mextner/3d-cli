LAYERS = 8
LAYER_H = 0.2


def _layer(n: int, tool_in: int) -> tuple[list[str], int]:
    """One layer: preamble (ends the open object, wipes, lifts), the part in `tool_in`, a tool
    change on the prime tower, the part in the other head."""
    z = round(n * LAYER_H, 3)
    other = 1 - tool_in
    out = [";LAYER_CHANGE", f";Z:{z}", f";HEIGHT:{LAYER_H}"]
    if n > 1:
        out += ["EXCLUDE_OBJECT_END NAME=box", "G1 X22 Y21 F9000 ; wipe", "G1 E-0.8 F1800", f"G1 Z{z + 0.4}"]
    out += [";AFTER_LAYER_CHANGE", f"M73 P{n * 10} R{LAYERS - n}", f"G1 Z{z}", "G1 X20 Y20 F12000"]
    out += ["G1 E0.8 F1800"] if n > 1 else []
    out += ["EXCLUDE_OBJECT_START NAME=box", ";TYPE:Outer wall", "G1 F3000",
            "G1 X40 Y20 E1.2", "G1 X40 Y40 E1.2", "G1 E-0.8 F1800", "EXCLUDE_OBJECT_END NAME=box",
            ";TYPE:Prime tower", f"G1 Z{z + 0.4}", "G1 X100 Y100 F12000", "G1 E-10 F1800",
            f"T{other}", f"SM_PRINT_PREEXTRUDE_FILAMENT INDEX={other}", f"M104 S170 T{tool_in}",
            "G1 E10 F1800", f"G1 Z{z}", "G1 X110 Y100 E0.6 F3000", "G1 X110 Y104 E0.3", "G1 E-0.8 F1800",
            "EXCLUDE_OBJECT_START NAME=box", ";TYPE:Inner wall", "G1 X20 Y40 F12000", "G1 E0.8 F1800",
            "G1 X20 Y20 E1.2 F3000", "G1 X38 Y20 E1.0"]
    return out, other


def synthetic_gcode() -> str:
    lines = ["; HEADER_BLOCK_START", "; generated by Snapmaker Orca 2.4.0", f"; total layer number: {LAYERS}",
             "; HEADER_BLOCK_END", "; filament_density: 1.24,1.27", "; EXECUTABLE_BLOCK_START",
             "EXCLUDE_OBJECT_DEFINE NAME=box CENTER=30,30 POLYGON=[[20,20],[40,20],[40,40],[20,40]]",
             "EXCLUDE_OBJECT_DEFINE NAME=gone CENTER=60,60 POLYGON=[[55,55],[65,55],[65,65],[55,65]]",
             "M140 S60", "M104 S210 T0", "M104 S215 T1", "M190 S60", "M109 S210 T0", "M109 S215 T1",
             "G90", "M83", "T0", "M106 S255", "SET_VELOCITY_LIMIT VELOCITY=300", "SET_PRESSURE_ADVANCE ADVANCE=0.04"]
    tool = 0
    for n in range(1, LAYERS + 1):
        body, tool = _layer(n, tool)
        lines += body
        lines.append(f"M109 S{215 if tool else 210} T{tool}")
    lines += ["EXCLUDE_OBJECT_END NAME=box", "; EXECUTABLE_BLOCK_END",
              "; filament used [mm] = 40.00, 40.00", "; filament used [cm3] = 0.10, 0.10",
              "; filament used [g] = 0.12, 0.12", "; filament cost = 2.00, 2.00",
              "; total filament used [g] = 0.24", "; total filament cost = 4.00",
              "; total filament change = 8", "; estimated printing time (normal mode) = 0h 8m 0s",
              "; CONFIG_BLOCK_START", "; layer_height = 0.2", "; CONFIG_BLOCK_END", ""]
    return "\n".join(lines)


@dataclass
class ResumeCheck:
    problems: list[str] = field(default_factory=list)
    z_travel: float = 0.0
    header_xy_moves: int = 0
    body_min_z: float = 1e9
    tower_extrusions: int = 0


_NUM = re.compile(r"([XYZEF])(-?\d*\.?\d+)")
_MOVE = re.compile(r"^G[01]\b")


def check_resume(text: str, zr: float, *, no_tower: bool = False) -> ResumeCheck:
    """Independent checks of a resume G-code: the header lifts Z (and only Z) before any X/Y
    move, tool change, purge or homing; no body move goes below the resume layer Z (modal Z
    through relative moves); every extrusion is at or above its layer's `;Z:`; objects are
    balanced; with --no-tower no prime-tower extrusion is left."""
    res = text.split("\n")
    out = ResumeCheck()
    problems = out.problems
    hdr_end = res.index("; ===== end of resume header: original G-code follows =====")
    hdr_start = next(i for i, ln in enumerate(res) if ln.startswith("; ===== RESUME of"))
    z: float | None = None
    xy_moves: list[tuple[int, float | None]] = []
    first_motion: tuple[int, dict[str, str]] | None = None
    rel = False
    for i in range(hdr_start, hdr_end):
        ln = res[i].split(";")[0].strip()
        if ln.startswith("G91"):
            rel = True
        if ln.startswith("G90"):
            rel = False
        if _MOVE.match(ln):
            p = dict(_NUM.findall(ln))
            if first_motion is None and any(k in p for k in "XYZ"):
                first_motion = (i, p)
            if "Z" in p:
                z = float(p["Z"]) if not rel else (z or 0) + float(p["Z"])
            if "X" in p or "Y" in p:
                xy_moves.append((i, z))
        if ln.startswith(("T", "SM_PRINT_PREEXTRUDE", "MOVE_TO", "G28")) and z is None:
            problems.append(f"header line {i + 1}: {ln} before any Z lift")
    if first_motion is None or set(first_motion[1]) - {"Z", "F"}:
        problems.append(f"first header motion is not Z-only: {first_motion}")
        return out
    out.z_travel = float(first_motion[1]["Z"])
    out.header_xy_moves = len(xy_moves)
    for i, zz in xy_moves:
        if zz is None or zz < out.z_travel - 1e-6:
            problems.append(f"header XY move at line {i + 1} below travel Z ({zz} < {out.z_travel})")
    rel = False                                  # Z carries on from the header (its last move is the start Z)
    layer_z = zr
    obj: str | None = None
    feat: str | None = None
    ext_below = 0
    for i in range(hdr_end + 1, len(res)):
        raw = res[i]
        ln = raw.split(";")[0].strip()
        if raw.startswith(";TYPE:"):
            feat = raw[6:]
        elif raw.startswith(";Z:"):
            layer_z = float(raw[3:])
        if ln.startswith("G91"):
            rel = True
        elif ln.startswith("G90"):
            rel = False
        elif ln.startswith("EXCLUDE_OBJECT_START"):
            if obj:
                problems.append(f"line {i + 1}: nested object")
            obj = ln
        elif ln.startswith("EXCLUDE_OBJECT_END"):
            if not obj:
                problems.append(f"line {i + 1}: EXCLUDE_OBJECT_END with no object open")
            obj = None
        elif _MOVE.match(ln):
            p = {k: float(v) for k, v in _NUM.findall(ln)}
            if "Z" in p:
                z = (z or 0.0) + p["Z"] if rel else p["Z"]
                out.body_min_z = min(out.body_min_z, z)
            if p.get("E", 0) > 0 and ("X" in p or "Y" in p):
                if z is None or z < zr - 1e-6:
                    ext_below += 1
                elif z < layer_z - 1e-6:
                    problems.append(f"line {i + 1}: extrusion at Z {z} below its layer Z {layer_z}")
                if feat == "Prime tower":
                    out.tower_extrusions += 1
    if out.body_min_z < zr - 1e-6:
        problems.append(f"body goes down to Z {out.body_min_z} < resume layer Z {zr}")
    if ext_below:
        problems.append(f"{ext_below} extrusions below Z {zr}")
    if no_tower and out.tower_extrusions:
        problems.append(f"--no-tower but {out.tower_extrusions} tower extrusions remain")
    return out
