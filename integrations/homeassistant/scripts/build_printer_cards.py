#!/usr/bin/env python3
"""Build the small, fixed printer-card module graph without runtime dependencies."""
from __future__ import annotations

import argparse
import hashlib
import json
import logging
import os
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor/webrtc-3.6.1"
OUTPUT = ROOT / "www/printer-cards/printer-cards.bundle.js"
BOOTSTRAP = ROOT / "www/printer-cards/printer-cards-bootstrap.js"
CONFIGURATION = ROOT / "snippets/configuration.3d.yaml"
CAMERA_TAG = "printer-webrtc-camera"


def replace_once(source: str, before: str, after: str) -> str:
    if source.count(before) != 1:
        raise ValueError(f"Module contract changed: expected one {before!r}")
    return source.replace(before, after, 1)


def without_exports(source: str) -> str:
    return re.sub(r"^export (?=(?:class|const|function) )", "", source, flags=re.MULTILINE)


def module_scope(source: str, exports: str) -> str:
    return f"const {{{exports}}} = (() => {{\n{without_exports(source)}\nreturn {{{exports}}};\n}})();\n"


def guarded_card(tag: str, source: str) -> str:
    return f"if (!customElements.get({json.dumps(tag)})) {{\n{source}\n}}\n"


def vendor_sources() -> dict[str, str]:
    manifest = json.loads((VENDOR / "sources.json").read_text(encoding="utf-8"))
    sources: dict[str, str] = {}
    for filename, expected in manifest["sha256"].items():
        data = (VENDOR / filename).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise ValueError(f"Pinned vendor input changed: {filename}: {actual} != {expected}")
        sources[filename] = data.decode("utf-8")
    return sources


def build_bundle() -> str:
    sources = vendor_sources()
    camera = replace_once(sources["webrtc-camera.js"], "import {VideoRTC} from './video-rtc.js?v=1.9.9';\n", "")
    camera = replace_once(camera, "import {DigitalPTZ} from './digital-ptz.js?v=3.3.0';\n", "")
    camera = replace_once(camera, "customElements.define('webrtc-camera', WebRTCCamera);", f"customElements.define('{CAMERA_TAG}-implementation', WebRTCCamera);")
    camera = replace_once(camera, "type: 'webrtc-camera',", f"type: '{CAMERA_TAG}',")
    camera = replace_once(camera, "name: 'WebRTC Camera',", "name: 'Printer Camera',")
    camera = replace_once(
        camera, "if (window.customCards) window.customCards.push(card);\nelse window.customCards = [card];",
        "window.customCards = window.customCards || [];\n"
        f"if (!window.customCards.some(entry => entry.type === '{CAMERA_TAG}')) window.customCards.push(card);",
    )
    share_dir = ROOT / "www/u1-share"
    share = replace_once(
        (share_dir / "u1-share-card.js").read_text(encoding="utf-8"),
        'import { MAX_TTL, CAMERA, publicOrigin, validateSignedPath, expiryFromPath, buildLinks } from "./share-common.js";\n', "",
    )
    share = replace_once(share, 'customElements.get("u1-share-card")', 'customElements.get("u1-share-card-implementation")')
    share = replace_once(share, 'customElements.define("u1-share-card",', 'customElements.define("u1-share-card-implementation",')
    share = replace_once(share, "window.customCards.push(", 'if (!window.customCards.some(entry => entry.type === "u1-share-card")) window.customCards.push(')
    inspector = (share_dir / "u1-inspector-card.js").read_text(encoding="utf-8")
    inspector = replace_once(inspector, "customElements.get('u1-inspector-card')", "customElements.get('u1-inspector-card-implementation')")
    inspector = replace_once(inspector, "customElements.define('u1-inspector-card',", "customElements.define('u1-inspector-card-implementation',")
    inspector = replace_once(inspector, "window.customCards.push(", "if (!window.customCards.some(entry => entry.type === 'u1-inspector-card')) window.customCards.push(")
    helper_exports = "MAX_TTL, CAMERA, publicOrigin, validateSignedPath, expiryFromPath, buildLinks"
    output = (
        "/* Generated by scripts/build_printer_cards.py; edit inputs, then rebuild.\n"
        " * WebRTC 3.6.1, commit ec268cd05e8c09280e2bcdd4b40c22146cca8361.\n"
        " * Camera registration uses an owned tag; local helper extraction is recorded in vendor sources.json.\n\n"
        + sources["LICENSE"] + "\n*/\n\n"
        + module_scope(sources["video-rtc.js"], "VideoRTC")
        + module_scope(sources["digital-ptz.js"], "DigitalPTZ")
        + guarded_card(CAMERA_TAG + "-implementation", camera)
        + guarded_card("u1-inspector-card-implementation", inspector)
        + "{\n" + module_scope((share_dir / "share-common.js").read_text(encoding="utf-8"), helper_exports)
        + guarded_card("u1-share-card-implementation", share) + "}\n"
    )
    if re.search(r"^\s*(?:import|export)\s", output, re.MULTILINE):
        raise ValueError("Bundle must be self-contained; unexpected module edge")
    return output


def update_outputs(check: bool) -> None:
    bundle = build_bundle()
    digest = hashlib.sha256(bundle.encode()).hexdigest()[:16]
    bootstrap = BOOTSTRAP.read_text(encoding="utf-8")
    expected_bootstrap, count = re.subn(r'const BUNDLE_VERSION = "[^"]+";', f'const BUNDLE_VERSION = "{digest}";', bootstrap)
    if count != 1:
        raise ValueError("Expected one bootstrap bundle version")
    bootstrap_digest = hashlib.sha256(expected_bootstrap.encode()).hexdigest()[:16]
    configuration = CONFIGURATION.read_text(encoding="utf-8")
    expected_configuration, count = re.subn(
        r"(/local/printer-cards/printer-cards-bootstrap\.js\?v=)[a-z0-9]+",
        lambda match: match[1] + bootstrap_digest, configuration,
    )
    if count != 2:
        raise ValueError("Expected the same bootstrap in frontend and Lovelace resources")
    if check:
        if (not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != bundle or
                bootstrap != expected_bootstrap or configuration != expected_configuration):
            raise ValueError("Stale printer-card bundle/version; run scripts/build_printer_cards.py")
        logging.info("PASS: pinned inputs, self-contained bundle and versioned bootstrap match (bundle version %s)", digest)
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(bundle, encoding="utf-8")
    BOOTSTRAP.write_text(expected_bootstrap, encoding="utf-8")
    CONFIGURATION.write_text(expected_configuration, encoding="utf-8")
    logging.info("Wrote %s (%s bytes), version %s", OUTPUT, len(bundle.encode()), digest)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify checked-in output without changing it")
    args = parser.parse_args()
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    log = Path(f"/tmp/build-printer-cards-{stamp}-{os.getpid()}.log")
    # Owner policy requires an automatic private /tmp log for every script run.
    descriptor = os.open(log, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    os.close(descriptor)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", handlers=[logging.FileHandler(log, encoding="utf-8"), logging.StreamHandler(sys.stderr)])
    started = time.monotonic()
    logging.info("Log: %s", log)
    try:
        update_outputs(args.check)
        return 0
    except (OSError, ValueError, KeyError) as error:
        logging.error("Build failed: %s", error)
        return 1
    finally:
        logging.info("Finished in %.3fs; log: %s", time.monotonic() - started, log)


if __name__ == "__main__":
    raise SystemExit(main())
