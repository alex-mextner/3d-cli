-- 0050_weighing (#163): the tare database — known empty-spool weights per vendor / spool kind /
-- net, each with its source and ± grams — and, per spool, which tare 3d-api wrote into
-- Spoolman's spool_weight (so a weighing can say where its tare came from).
--
-- Seed: every distinct (manufacturer, spool_type, net weight, spool_weight) in SpoolmanDB
-- (https://github.com/Donkie/SpoolmanDB, the community filament DB Spoolman ships), read from
-- Spoolman 0.27.0 GET /api/v1/external/filament on 2026-10-14 (8120 filaments, 151 distinct
-- rows). σ 10 g is our assumption for spool-to-spool variance [not measured]. New sourced or
-- weighed values go in with `3d printops tare add`; a later seed refresh is a new migration.

CREATE TABLE spool_tare (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    vendor TEXT NOT NULL,             -- as the source names it ("Bambu Lab")
    vendor_key TEXT NOT NULL,         -- lower-case alphanumerics only ("bambulab"), for matching
    spool_kind TEXT CHECK (spool_kind IS NULL OR spool_kind IN ('cardboard', 'plastic', 'refill')),
    net_g REAL CHECK (net_g IS NULL OR net_g > 0),   -- nominal filament net the spool is sold with
    tare_g REAL NOT NULL CHECK (tare_g > 0),
    sigma_g REAL NOT NULL CHECK (sigma_g >= 0),
    source TEXT NOT NULL,             -- URL / "weighed empty spool on the kitchen scale" / …
    note TEXT,
    created_at TEXT NOT NULL,
    actor TEXT NOT NULL,
    archived INTEGER NOT NULL DEFAULT 0 CHECK (archived IN (0, 1))
);

CREATE INDEX spool_tare_vendor ON spool_tare (vendor_key);

-- The tare 3d-api last wrote into Spoolman spool.spool_weight, with its provenance. When the
-- Spoolman value no longer equals tare_g, someone edited it by hand and it counts as unsourced.
CREATE TABLE spool_tare_choice (
    spool_id INTEGER PRIMARY KEY,     -- Spoolman spool id
    tare_g REAL NOT NULL CHECK (tare_g > 0),
    sigma_g REAL NOT NULL CHECK (sigma_g >= 0),
    source TEXT NOT NULL,
    tare_id INTEGER REFERENCES spool_tare (id),
    at TEXT NOT NULL,
    actor TEXT NOT NULL
);

