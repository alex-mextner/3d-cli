def test_state_at_layer_is_the_first_extrusion_of_that_layer(tmp_path: Path) -> None:
    g = tmp_path / "plate.gcode"
    g.write_text(orca_gcode())
    cur = state_at(g, layer=3)
    st = cur.state
    assert (cur.layer, cur.z) == (3, 0.6)
    assert st["tool"] == 2 and st["temp"] == {0: 215.0, 2: 220.0} and st["bed"] == 65.0 and st["chamber"] == 40.0
    assert st["feature"] == "Outer wall" and st["fe"] == 3000.0 and st["fan"] == {0: 204.0}
    assert (st["width"], st["height"]) == (0.42, 0.2)


def test_state_at_byte_is_the_state_before_the_line_holding_it(tmp_path: Path) -> None:
    text = orca_gcode()
    g = tmp_path / "plate.gcode"
    g.write_text(text)
    cur = state_at(g, byte=byte_of(text, "G1 X30 Y30 E0.6", nth=2) + 3)  # inside layer 2's 2nd infill line
    st = cur.state
    assert (cur.layer, cur.z) == (2, 0.4)
    assert st["feature"] == "Sparse infill" and st["fe"] == 6000.0 and st["width"] == 0.45
    with pytest.raises(ValueError, match="past the end"):
        state_at(g, byte=len(text.encode()) + 10)
    with pytest.raises(ValueError, match="no layer 9"):
        state_at(g, layer=9)
    with pytest.raises(ValueError, match="exactly one"):
        state_at(g)


