def _slice(tmp: Path, log: str = LOG) -> tuple[Path, Path, Path, Path]:
    gcode = tmp / "lawn.gcode"
    gcode.write_text("; generated by Snapmaker Orca 2.4.0\nG28\nG1 X1 Y1 E1\n", encoding="utf-8")
    (tmp / "slice.log").write_text(log, encoding="utf-8")
    (tmp / "result.json").write_text(json.dumps(RESULT), encoding="utf-8")
    with zipfile.ZipFile(tmp / "sliced.3mf", "w") as z:
        z.writestr("Metadata/slice_info.config", SLICE_INFO)
    return gcode, tmp / "slice.log", tmp / "result.json", tmp / "sliced.3mf"


def test_record_keeps_every_slicer_warning_and_files_host_noise_apart(tmp_path: Path) -> None:
    gcode, log, res, sliced = _slice(tmp_path)
    rec = record(gcode, logs=[("slice.log", log.read_text())], results=[res], sliced_3mfs=[sliced])
    messages = {w.message: w for w in rec.warnings}
    assert set(messages) == {
        "can not find system preset file: /opt/snapmaker_orca/resources/profiles/BBL/machine_full/"
        "Creality K1 SE 0.4 nozzle.json",
        "no filament colors found in projects",
        "calc_exclude_triangles:Unable to create exclude triangles",
        "bed_temperature_too_high_than_filament",
    }
    assert messages["calc_exclude_triangles:Unable to create exclude triangles"].level == "error"
    assert messages["bed_temperature_too_high_than_filament"].error_code == "1000C001"
    assert {i.rule for i in rec.ignored} == {
        "CLI version banner", "headless display: Wayland/X11", "headless display: OpenGL/GLEW/GLFW"
    }
    data = json.loads(sidecar_path(gcode).read_text())
    assert sidecar_path(gcode).name == "lawn.slice-warnings.json"
    assert data["gcode_sha256"] == sha256_file(gcode) and data["slicer"] == "Snapmaker Orca 2.4.0"


def test_preflight_gate_fails_until_each_warning_is_accepted(tmp_path: Path) -> None:
    gcode, log, res, sliced = _slice(tmp_path)
    assert evaluate(gcode)[0] == "FAIL" and "never recorded" in evaluate(gcode)[1]
    rec = record(gcode, logs=[("slice.log", log.read_text())], results=[res], sliced_3mfs=[sliced])
    status, detail, lines = evaluate(gcode)
    assert status == "FAIL" and detail.startswith("4 of 4 slicer warning(s) not resolved")
    assert all(line.startswith("OPEN ") for line in lines)
    for w in rec.warnings:
        accept_warning(gcode, w.id, f"checked {w.id} in the preview")
    status, detail, lines = evaluate(gcode)
    assert status == "PASS" and "each accepted with a reason" in detail
    assert all("— accepted: checked" in line for line in lines)


def test_a_resliced_gcode_makes_the_sidecar_stale(tmp_path: Path) -> None:
    gcode, log, res, sliced = _slice(tmp_path)
    record(gcode, logs=[("slice.log", log.read_text())])
    gcode.write_text(gcode.read_text() + "G1 X2 Y2 E1\n", encoding="utf-8")
    status, detail, _ = evaluate(gcode)
    assert status == "FAIL" and "stale" in detail
    with pytest.raises(SidecarError, match="stale"):
        accept_warning(gcode, warning_id("warning", "no filament colors found in projects"), "fine")


def test_acceptances_carry_over_to_the_same_message_only(tmp_path: Path) -> None:
    gcode, log, _, _ = _slice(tmp_path)
    colours = warning_id("warning", "no filament colors found in projects")
    record(gcode, logs=[("slice.log", LOG)], accept={colours: "colours are set per head on the printer"})
    second = record(gcode, logs=[("slice.log", LOG + "[2026-10-14 13:31:00.0] [0x1] [warning] new one\n")])
    by_id = {w.id: w for w in second.warnings}
    assert (by_id[colours].accepted or {}).get("reason", "").startswith("colours are set")
    assert by_id[warning_id("warning", "new one")].accepted is None
    assert any("carried over" in n for n in second.notes)


def test_an_acceptance_needs_a_reason_and_a_known_id(tmp_path: Path) -> None:
    gcode, log, _, _ = _slice(tmp_path)
    record(gcode, logs=[("slice.log", LOG)])
    with pytest.raises(SidecarError, match="needs a reason"):
        accept_warning(gcode, warning_id("warning", "no filament colors found in projects"), " ")
    with pytest.raises(SidecarError, match="has no warning wdeadbeef"):
        accept_warning(gcode, "wdeadbeef", "a reason")


def test_a_hand_edited_acceptance_without_a_reason_stays_open(tmp_path: Path) -> None:
    gcode, log, _, _ = _slice(tmp_path)
    record(gcode, logs=[("slice.log", LOG)])
    side = sidecar_path(gcode)
    data = json.loads(side.read_text())
    for w, acc in zip(data["warnings"], [{"reason": ""}, {"x": "y"}, {"reason": 123}, {"reason": None}], strict=False):
        w["accepted"] = acc
    side.write_text(json.dumps(data))
    status, _, lines = evaluate(gcode)
    assert status == "FAIL" and all(line.startswith("OPEN ") for line in lines)


def test_concurrent_acceptances_are_all_kept(tmp_path: Path) -> None:
    from concurrent.futures import ProcessPoolExecutor

    gcode, log, _, _ = _slice(tmp_path)
    rec = record(gcode, logs=[("slice.log", LOG)])
    with ProcessPoolExecutor(len(rec.warnings)) as pool:
        list(pool.map(accept_warning, [gcode] * len(rec.warnings), [w.id for w in rec.warnings],
                      [f"checked {w.id}" for w in rec.warnings]))
    assert evaluate(gcode)[0] == "PASS"


def test_ids_ignore_plate_prefix_and_source_line_of_the_logger() -> None:
    assert warning_id("warning", "plate 1: found NON_CRITICAL slicing warnings: Floating regions") == warning_id(
        "warning", "Floating regions"
    )
    assert warning_id("warning", "run:2206, x") == warning_id("warning", "run:2310, x")
    assert warning_id("warning", "x") != warning_id("error", "x")


def test_a_multi_line_message_is_one_warning() -> None:
    text = (
        "[2026-10-14 13:31:00.0] [0x1] [warning] plate 1: found slicing warnings: Floating regions\n"
        "object BASE3 layer 12\n"
        "[2026-10-14 13:31:00.1] [0x1] [info] next\n"
    )
    assert parse_log(text) == [("warning", "plate 1: found slicing warnings: Floating regions\nobject BASE3 layer 12")]


def test_a_failed_slice_is_an_error_from_result_json(tmp_path: Path) -> None:
    gcode, _, res, _ = _slice(tmp_path)
    res.write_text(json.dumps({"return_code": -100, "error_string": "Found slicing result conflict!",
                               "sliced_plates": [{"id": 1, "warning_message": "Floating regions"}]}))
    rec = record(gcode, results=[res])
    assert [(w.level, w.message) for w in rec.warnings] == [
        ("error", "slicer exit -100: Found slicing result conflict!"),
        ("warning", "Floating regions"),
    ]


def test_record_without_any_slicer_output_is_refused(tmp_path: Path) -> None:
    gcode, _, _, _ = _slice(tmp_path)
    with pytest.raises(SidecarError, match="no slicer output"):
        record(gcode)


def test_a_current_sidecar_follows_a_thumbnail_edit_a_stale_one_does_not(tmp_path: Path) -> None:
    gcode, log, _, _ = _slice(tmp_path)
    record(gcode, logs=[("slice.log", LOG)])
    old = sha256_file(gcode)
    gcode.write_text("; thumbnail\n" + gcode.read_text(), encoding="utf-8")
    assert follow_edit(gcode, gcode, old, sha256_file(gcode), "gcode-thumbnails add") == sidecar_path(gcode)
    assert evaluate(gcode)[1].startswith("3 of 3 slicer warning(s) not resolved")  # current again, not stale
    data = json.loads(sidecar_path(gcode).read_text())
    assert data["post_processed"] == [{"step": "gcode-thumbnails add", "from_sha256": old}]
    assert follow_edit(gcode, gcode, old, "0" * 64, "gcode-thumbnails add") is None
