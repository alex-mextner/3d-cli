"""routes_vision.py — the last camera-vision verdict of a fleet printer (Home Assistant sensors).

  GET /v1/printers/{name}/vision   scope read. The status file `3d printer vision NAME` keeps
                                   (printer_ops/vision_status.py): printer state, last frame's
                                   p / q / trend / findings, frames scored, event counts by kind,
                                   the last event, plus `age_s` (seconds since it was written).
                                   404 unknown printer, or the live loop never ran for it.

Read-only; it never contacts a printer. The file lives in the state dir of the process that runs
this API (`$XDG_STATE_HOME/3d-cli/vision/NAME.json`), so the vision loop and the API must see the
same state dir (same user and host, or a shared mount). The HA package generated by
`3d ha vision` (lib/ha_vision.py) reads this route for every fleet printer that has a camera.
"""

from __future__ import annotations

import time
from typing import Any

from fastapi import APIRouter, Depends, HTTPException

from printer_ops.vision_status import read_status
from printops.api.deps import require
from printops.fleet import FleetError, load_fleet

router = APIRouter()
READ = [Depends(require("read"))]


@router.get("/v1/printers/{name}/vision", dependencies=READ)
def printer_vision(name: str) -> dict[str, Any]:
    try:
        fleet = load_fleet()
    except FleetError as e:
        raise HTTPException(503, f"fleet registry unreadable: {e.message}") from e
    if fleet is not None and name not in fleet.printers:
        raise HTTPException(404, f"unknown printer {name!r}")
    doc = read_status(name)
    if doc is None:
        raise HTTPException(
            404,
            f"no vision status for {name!r}: `3d printer vision {name}` has not run",
        )
    return {**doc, "age_s": round(max(0.0, time.time() - float(doc["ts"])), 1)}
