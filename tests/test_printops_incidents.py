def make_spool(sm: FakeSpoolman, *, vendor: str = "Elegoo", material: str = "PLA+", name: str = "Green",
               lot: str | None = "L2409", extra: dict[str, Any] | None = None) -> dict[str, Any]:
    v = next((x for x in sm.find("vendor") if x["name"] == vendor), None) or sm.create("vendor", {"name": vendor})
    f = next((x for x in sm.find("filament") if x["name"] == name and x["vendor"]["id"] == v["id"]), None) or sm.create(
        "filament", {"name": name, "vendor_id": v["id"], "material": material, "density": 1.24, "diameter": 1.75,
                     "weight": 1000})
    data: dict[str, Any] = {"filament_id": f["id"], "extra": {k: encode_extra(x) for k, x in (extra or {}).items()}}
    if lot:
        data["lot_nr"] = lot
    return sm.create("spool", data)


def printing_u1(filename: str, *, size: int, position: int | None, layer: int | None) -> dict[str, Any]:
    st = u1_status("printing", filename, 0.42)
    st["print_stats"]["info"] = {"current_layer": layer, "total_layer": 4}
    st["virtual_sdcard"].update(file_size=size, file_path=f"/home/lava/printer_data/gcodes/{filename}")
    if position is not None:
        st["virtual_sdcard"]["file_position"] = position
    st["extruder2"] = {"temperature": 219.4, "target": 220.0}
    st["heater_bed"] = {"temperature": 64.8, "target": 65.0}
    return st


def readers_for(status: dict[str, Any], dirs: tuple[Path, ...], *, history: list[dict[str, Any]] | None = None,
                humidity: HaStates | None = None) -> tuple[Readers, list[str]]:
    calls: list[str] = []

    def get(_device: Any, path: str) -> Any:
        calls.append(path)
        return {"count": len(history or []), "jobs": history or []}

    def stat(_device: Any) -> Any:
        calls.append("status")
        return parse_status(status)

    return Readers(status=stat, moonraker=get, gcode_dirs=dirs, humidity=humidity), calls


def hashed_name(path: Path) -> str:
    """How `3d printer upload` names the file on the printer: <stem>-<16 hex of SHA-256>.gcode."""
    return f"{path.stem}-{hashlib.sha256(path.read_bytes()).hexdigest()[:16]}.gcode"


def test_context_from_fake_u1_status_and_gcode_fills_job_layer_temps_spool_lot_drying(
    tmp_path: Path, fleet: Path, sm: FakeSpoolman, printops_db: sqlite3.Connection
) -> None:
    text = orca_gcode()
    g = tmp_path / "gcodes" / "plate.gcode"
    g.parent.mkdir()
    g.write_text(text)
    remote = hashed_name(g)
    dried = (datetime.datetime.now(UTC) - datetime.timedelta(days=3)).isoformat()
    spool = make_spool(sm, extra={"printops_slot": "u1/T3", "last_dried_at": dried})
    status = printing_u1(remote, size=g.stat().st_size, position=byte_of(text, "G1 X30 Y30 E0.6", nth=3) + 1, layer=3)
    history = [{"job_id": "00005A", "filename": remote, "status": "in_progress"}]
    rd, calls = readers_for(status, (g.parent,), history=history)

    ctx = resolve(printops_db, sm, printer="u1", head="t3", readers=rd)

    f = ctx.fields
    assert (f["printer"], f["head"], f["job_file"], f["job_id"], f["layer"], f["z_mm"]) == ("u1", "T3", remote, "00005A", 3, 0.6)
    assert (f["feature"], f["nozzle_temp"], f["bed_temp"], f["chamber_temp"], f["fan_pct"]) == ("sparse infill", 220.0, 65.0, 40.0, 80.0)
    assert f["speed_mm_s"] == 100.0 and f["volumetric_mm3_s"] == round(100 * bead_area(0.45, 0.2), 2)  # type: ignore[operator]
    assert (f["spool_id"], f["vendor"], f["material"], f["filament_name"], f["lot_nr"]) == (spool["id"], "Elegoo", "PLA+", "Green", "L2409")
    assert f["days_since_dried"] == pytest.approx(3, abs=0.01)
    assert "SHA-256" in ctx.gcode["how"] and ctx.gcode["gcode_layer"] == 3  # type: ignore[index]
    assert ctx.sources["layer"].startswith("u1 status") and "M104/M109" in ctx.sources["nozzle_temp"]
    assert ctx.telemetry["nozzle"] == {"heater": "extruder2", "actual": 219.4, "target": 220.0}
    assert calls == ["status", "/server/history/list?limit=1&order=desc"]  # read-only, two requests


@pytest.mark.skipif(not REAL_GCODE.is_file(), reason=f"real babushkin-dom G-code absent: {REAL_GCODE}")
def test_context_on_real_babushkin_dom_gcode(tmp_path: Path, fleet: Path, sm: FakeSpoolman,
                                             printops_db: sqlite3.Connection) -> None:
    raw = REAL_GCODE.read_bytes()
    lines = raw.split(b"\n")
    # independent scan: the 5th layer's ;Z: and the only tool the plate uses (T3 = head T4)
    starts = [i for i, ln in enumerate(lines) if ln.startswith(b";LAYER_CHANGE")]
    z5 = float(next(ln for ln in lines[starts[4]:] if ln.startswith(b";Z:"))[3:])
    tools = {ln.strip() for ln in lines if ln.strip() in (b"T0", b"T1", b"T2", b"T3")}
    assert tools == {b"T3"}
    make_spool(sm, vendor="Snapmaker", material="PLA", name="PLA Basic Green", lot="SM-2410",
               extra={"printops_slot": "u1/T4"})
    status = printing_u1(REAL_GCODE.name, size=len(raw), position=None, layer=5)
    rd, _ = readers_for(status, (REAL_GCODE.parent,))
    ctx = resolve(printops_db, sm, printer="u1", readers=rd)  # head: from the G-code's active tool
    f = ctx.fields
    assert f["head"] == "T4" and "active tool T3" in ctx.sources["head"]
    assert f["layer"] == 5 and f["z_mm"] == z5 and f["lot_nr"] == "SM-2410"
    assert f["feature"] and f["nozzle_temp"] >= 150 and f["bed_temp"] > 0
    assert f["speed_mm_s"] > 0 and f["volumetric_mm3_s"] > 0
    # the same G-code at the printer's byte cursor in the middle of the file
    mid = len(raw) // 2
    status = printing_u1(REAL_GCODE.name, size=len(raw), position=mid, layer=None)
    rd, _ = readers_for(status, (REAL_GCODE.parent,))
    ctx = resolve(printops_db, sm, printer="u1", head="T4", readers=rd)
    expected_layer = sum(1 for i in starts if len(b"\n".join(lines[:i])) < mid)
    assert ctx.fields["layer"] == expected_layer and ctx.gcode["byte"] <= mid  # type: ignore[index]


