"""layers.py — adaptive layer-height plan for one object, in the exact form Snapmaker Orca reads from a 3MF.

WHAT: `plan_layers(mesh, ...)` turns the surface slope of a model into a per-object layer-height profile:
  fine layers (`hmin`) only on the steepest-rounded surfaces, coarse (`hmax`) on walls, capped at `mix_cap` inside the
  z-ranges where a mixed-colour part exists, neighbouring layers limited by a Lipschitz slope. The result
  (`LayerPlan`) carries the layer heights/tops Orca will generate (a port of its `generate_object_layers`) and the
  text of `Metadata/layer_heights_profile.txt`.
  `mix_zranges_from(parts)` derives the capped z-ranges from the colour parts (`prep.regions.split_parts`);
  `LayerPlan.heights_between` gives the layers printed over a part, which `prep.regions.check_mixes` judges.
WHY: uniform 0.08 mm layers on the 92 mm Chekhov cat is ~1150 layers; the adaptive plan keeps 0.08 on the few
  domes where stair-steps show and runs 0.24-0.32 on the walls. Mixed colours (a Full Spectrum cycle prints one
  filament per layer) read as a blend only when each layer is thin, so the layers over a mixed part are capped.
METRIC (stair-step visibility, port of Chekhov u1/layer_profile.py): a facet whose normal has vertical component
  n_z = |cos(tilt)| leaves a stair-step cusp of about h * n_z, so the layer height keeping the cusp at tolerance c
  is h = c / n_z. Flat facets (n_z >= flat_eps) are skipped: a horizontal top has no step error, the shells cover it.
  Vertical walls (n_z ~ 0) take hmax. Down-facing slopes count the same (|n_z|). Per z-slab (0.05 mm) the severity s(z)
  is the 90th area-weighted percentile of n_z over the sloped facets crossing the slab (slabs with < 2 mm of sloped
  surface per mm of height count as 0), box-smoothed over 0.6 mm. h(z) falls linearly from hmax (s <= r0 * s_thin)
  to hmin (s >= s_thin). `s_thin` is the (1 - hmin_fraction) quantile of the positive severities, floored at 0.85
  (tilt <= 32 deg from horizontal): hmin is reached only on the steepest few percent of the part height, and a
  model with no real domes never gets hmin at all (a vertical cylinder is hmax everywhere).
  The geometry worktree's `layer_heights.py` (0.5 mm bins, a curvature proxy from a per-face KD-tree ball query,
  hand-picked 0.16/0.24/0.28 tiers) is NOT ported: its Python loop over every face is the slow part, and its extra
  gate (curvature) only exempts planar ramps, which stair-step as visibly as domes. The slope metric below is the
  one Chekhov u1 shipped (its `simulate_layers` was checked against the real G-code by u1/verify_gcode.py).
ORCA FORMAT AND QUIRKS (01.10.01.50, found on the Chekhov U1 builds):
  * `Metadata/layer_heights_profile.txt` holds one line per object: `object_id=<1-based index>|z0;h0;z1;h1;...\\n`,
    values `%f`, piecewise-linear h(z) with z measured from the object bottom. Object ids count objects in the 3MF
    in order; the whole cat is ONE multi-part object (colours are parts), because the prime tower compares the
    profiles of all objects (Print.cpp:1745) and a variable profile is per object.
  * The last z MUST equal the object height within 1e-3, otherwise Orca silently drops the profile.
  * Layer ranges (`layer_config_ranges.xml`) segfault the CLI: never use them, the profile alone carries the plan.
  * Layers are generated by `generate_object_layers` (Slicing.cpp): the first layer is fixed at
    `initial_layer_print_height`, each next height is the profile lerped at `print_z + min_layer_height / 2`. Hence the
    z-ranges of mixed parts are extended by `mix_margin`, and `first_height` must be written to the process as
    `initial_layer_print_height` (it is lowered to `mix_cap` when a mixed part starts on the bed).
  * Mixed-filament patterns are indexed by layer NUMBER, not height (MixedFilament::resolve): a mix shifts its
    optical ratio wherever the thickness changes inside one pattern period, which the Lipschitz limit keeps small.
INVARIANTS:
  * The mesh is in the print frame (lowest point at z = 0); z-ranges are in the same frame.
  * Every layer overlapping a mix range is <= `mix_cap` (+ 5e-4 mm); `plan_layers` verifies it on the simulated
    layers and returns FAIL otherwise.
  * `heights`, `z_tops` and `profile_text` agree: re-simulating the parsed text gives `z_tops` (the profile is
    rounded to 1e-4 mm BEFORE it is simulated).
Past bugs: none yet.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any, NamedTuple

import numpy as np
import trimesh
from numpy.typing import NDArray

from errors import InvalidArgument
from prep.contracts import Part, Verdict

CMD_NAME = "prep"
#: z-slab thickness of the severity scan, mm
SLAB_MM = 0.05
#: a layer over a mixed part may exceed the cap by this much (profile text rounds to 1e-4 mm)
CAP_SLACK_MM = 5e-4
#: the stack is landed on the object top within this (half the thinnest layer is the best any stack can do)
TOP_WARN_FRACTION = 0.5
#: the tail of the object (mm) whose layers are scaled to land the stack on the top
TAIL_MM = 3.0
Floats = NDArray[np.float64]


# ---------------------------------------------------------------------------------------------- severity
class _Severity(NamedTuple):
    z: Floats  # slab centres, mm from the object bottom
    s: Floats  # smoothed severity per slab, 0..1
    height: float


def _severity(
    mesh: trimesh.Trimesh,
    *,
    flat_eps: float = 0.995,
    pct: float = 0.90,
    min_length: float = 2.0,
    smooth_mm: float = 0.6,
) -> _Severity:
    """Per z-slab severity: smoothed area-weighted `pct` percentile of |n_z| over the sloped facets crossing it."""
    v = np.asarray(mesh.vertices, dtype=np.float64)
    tri = v[np.asarray(mesh.faces, dtype=np.int64)]
    normal = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    length = np.linalg.norm(normal, axis=1)
    nz = np.zeros(len(tri))
    ok = length > 1e-12
    nz[ok] = np.abs(normal[ok, 2]) / length[ok]
    area = 0.5 * length
    zlo = float(v[:, 2].min())
    height = float(v[:, 2].max()) - zlo
    keep = ok & (nz < flat_eps)
    area, nz = area[keep], nz[keep]
    z0 = tri[keep][:, :, 2].min(axis=1) - zlo
    z1 = tri[keep][:, :, 2].max(axis=1) - zlo
    n_slab = max(1, int(np.ceil(height / SLAB_MM)))
    if not keep.any():  # only flat facets: no stair-steps anywhere
        centres = np.asarray((np.arange(n_slab) + 0.5) * SLAB_MM, dtype=np.float64)
        return _Severity(centres, np.zeros(n_slab), height)
    i0 = np.clip((z0 / SLAB_MM).astype(np.int64), 0, n_slab - 1)
    i1 = np.clip((z1 / SLAB_MM).astype(np.int64), 0, n_slab - 1)
    cnt = i1 - i0 + 1
    rep = np.repeat(np.arange(len(area)), cnt)
    off = np.arange(int(cnt.sum())) - np.repeat(np.cumsum(cnt) - cnt, cnt)
    slab = i0[rep] + off
    weight = area[rep] / cnt[rep]
    value = nz[rep]
    order = np.lexsort((value, slab))
    slab, value, weight = slab[order], value[order], weight[order]
    total = np.bincount(slab, weights=weight, minlength=n_slab)
    base = np.concatenate([[0.0], np.cumsum(total)[:-1]])
    cum = np.cumsum(weight)
    pick = np.clip(
        np.searchsorted(cum, base + pct * total, side="left"), 0, len(value) - 1
    )
    # `total / SLAB_MM` = sloped surface per mm of height; thin slivers do not count
    s = np.where(total / SLAB_MM >= min_length, value[pick], 0.0)
    k = max(1, round(smooth_mm / SLAB_MM))
    kernel = np.ones(2 * k + 1) / (2 * k + 1)
    smooth = np.convolve(np.pad(s, k, mode="edge"), kernel, mode="same")[k:-k]
    z_centres = np.asarray((np.arange(n_slab) + 0.5) * SLAB_MM, dtype=np.float64)
    return _Severity(z_centres, np.asarray(smooth, dtype=np.float64), height)


def _lipschitz(h: Floats, slope: float, dz: float) -> Floats:
    """The largest curve <= h that changes by at most `slope` mm per mm of z (two-pass min-plus envelope)."""
    idx = np.arange(len(h)) * (slope * dz)
    forward = np.minimum.accumulate(h - idx) + idx
    back = forward[::-1]
    return np.asarray((np.minimum.accumulate(back - idx) + idx)[::-1], dtype=np.float64)


# ---------------------------------------------------------------------------------------------- Orca model
def simulate_layers(
    zs: Sequence[float] | Floats,
    hs: Sequence[float] | Floats,
    height: float,
    first: float,
    min_layer_height: float,
) -> Floats:
    """Layer tops Orca generates from a profile (Slicing.cpp `generate_object_layers`): the first layer is fixed
    at `first`, every next height is the profile lerped at `print_z + min_layer_height / 2`; generation stops
    when that point would reach the object top."""
    tops = [first]
    print_z = first
    idx = 0
    n = len(zs)
    slice_z = print_z + 0.5 * min_layer_height
    while slice_z < height:
        nxt = idx + 1
        while nxt < n and slice_z >= zs[nxt]:
            idx, nxt = nxt, nxt + 1
        h = hs[idx]
        if nxt < n:
            h = hs[idx] + (hs[nxt] - hs[idx]) * (slice_z - zs[idx]) / (
                zs[nxt] - zs[idx]
            )
        slice_z = print_z + 0.5 * h
        if slice_z >= height:
            break
        print_z += h
        tops.append(print_z)
        slice_z = print_z + 0.5 * min_layer_height
    return np.array(tops)


def _compress(zs: Floats, hs: Floats, tol: float) -> tuple[Floats, Floats]:
    """Douglas-Peucker on (z, h): the fewest points whose piecewise-linear curve stays within `tol` of h(z)."""
    keep = np.zeros(len(zs), dtype=bool)
    keep[[0, -1]] = True
    stack = [(0, len(zs) - 1)]
    while stack:
        a, b = stack.pop()
        if b - a < 2:
            continue
        lin = hs[a] + (hs[b] - hs[a]) * (zs[a + 1 : b] - zs[a]) / (zs[b] - zs[a])
        err = np.abs(lin - hs[a + 1 : b])
        k = int(err.argmax())
        if err[k] > tol:
            keep[a + 1 + k] = True
            stack += [(a, a + 1 + k), (a + 1 + k, b)]
    return zs[keep], hs[keep]


# ---------------------------------------------------------------------------------------------- profile text
def profile_text_of(profile: Sequence[tuple[float, float]], object_id: int = 1) -> str:
    """One line of `Metadata/layer_heights_profile.txt`: `object_id=N|z0;h0;z1;h1;...` + newline, `%f` values."""
    return (
        f"object_id={object_id}|"
        + ";".join(f"{v:f}" for z, h in profile for v in (z, h))
        + "\n"
    )


def parse_profile_text(text: str) -> tuple[int, tuple[tuple[float, float], ...]]:
    """Inverse of `profile_text_of` for a single-object file: (object id, ((z, h), ...))."""
    line = text.strip()
    head, sep, body = line.partition("|")
    if not sep or not head.startswith("object_id="):
        raise InvalidArgument(
            "layer profile",
            line[:40],
            ["object_id=<n>|z0;h0;z1;h1;..."],
            command=CMD_NAME,
        )
    try:
        object_id = int(head[len("object_id=") :])
        values = [float(x) for x in body.split(";")]
    except ValueError as exc:
        raise InvalidArgument(
            "layer profile",
            line[:40],
            ["object_id=<n>|z0;h0;z1;h1;..."],
            command=CMD_NAME,
        ) from exc
    if len(values) < 4 or len(values) % 2:
        raise InvalidArgument(
            "layer profile",
            f"{len(values)} values",
            ["an even number (>= 4) of z;h values"],
            command=CMD_NAME,
        )
    return object_id, tuple(
        (values[i], values[i + 1]) for i in range(0, len(values), 2)
    )


# ---------------------------------------------------------------------------------------------- mix ranges
def mix_zranges_from(parts: Sequence[Part]) -> tuple[tuple[float, float], ...]:
    """z-extent of every part that prints a mix (`Assign.mix`), overlapping ranges merged, sorted by z."""
    spans = sorted(
        (float(p.mesh.bounds[0][2]), float(p.mesh.bounds[1][2]))
        for p in parts
        if p.assign.mix is not None
    )
    merged: list[list[float]] = []
    for lo, hi in spans:
        if merged and lo <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], hi)
        else:
            merged.append([lo, hi])
    return tuple((lo, hi) for lo, hi in merged)


# ---------------------------------------------------------------------------------------------- the step result
@dataclass
class LayerPlan:
    """Result of `plan_layers`. `heights[i]` is layer i (layer 0 is the fixed first layer), `z_tops[i]` its top."""

    verdict: Verdict
    reasons: tuple[str, ...]
    heights: tuple[float, ...]
    z_tops: tuple[float, ...]
    profile: tuple[tuple[float, float], ...]
    profile_text: str
    height_mm: float
    first_height: float
    hmin: float
    hmax: float
    slope: float
    mix_cap: float
    mix_zranges: tuple[tuple[float, float], ...]
    stats: dict[str, Any]

    @property
    def top_error(self) -> float:
        """Top of the last layer minus the object height (mm; Orca lands within about half a layer)."""
        return self.z_tops[-1] - self.height_mm

    def heights_between(self, z_lo: float, z_hi: float) -> tuple[float, ...]:
        """Heights of the layers printed over [z_lo, z_hi] (every layer overlapping the range)."""
        bottoms = (0.0, *self.z_tops[:-1])
        return tuple(
            h
            for h, b, t in zip(self.heights, bottoms, self.z_tops, strict=True)
            if b < z_hi and t > z_lo
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "verdict": self.verdict,
            "reasons": list(self.reasons),
            "layers": len(self.heights),
            "heights": [round(h, 4) for h in self.heights],
            "z_tops": [round(z, 4) for z in self.z_tops],
            "profile_text": self.profile_text,
            "height_mm": round(self.height_mm, 4),
            "first_height": round(self.first_height, 4),
            "top_error": round(self.top_error, 4),
            "hmin": self.hmin,
            "hmax": self.hmax,
            "slope": self.slope,
            "mix_cap": self.mix_cap,
            "mix_zranges": [
                [round(lo, 4), round(hi, 4)] for lo, hi in self.mix_zranges
            ],
            "stats": self.stats,
        }

    def summary(self) -> str:
        s = self.stats
        text = (
            f"{s['layers']} layers, {s['at_hmin_pct']:.1f}% at {self.hmin:g} mm, median {s['median']:.2f} mm, "
            f"top error {self.top_error:+.3f} mm"
        )
        if self.mix_zranges:
            text += (
                f", {len(self.mix_zranges)} mix zone(s) capped at {self.mix_cap:g} mm"
            )
        if self.verdict != "PASS" and self.reasons:
            text += f" — {self.reasons[0]}"
        return text


def _check_params(
    hmin: float,
    hmax: float,
    first: float,
    slope: float,
    mix_cap: float,
    hmin_fraction: float,
) -> None:
    if not 0 < hmin <= hmax:
        raise InvalidArgument(
            "layer heights",
            f"hmin={hmin} hmax={hmax}",
            ["0 < hmin <= hmax (mm)"],
            command=CMD_NAME,
        )
    if first <= 0:
        raise InvalidArgument(
            "first layer", str(first), ["a positive height in mm"], command=CMD_NAME
        )
    if slope <= 0:
        raise InvalidArgument(
            "slope",
            str(slope),
            ["a positive number (mm of layer height per mm of z)"],
            command=CMD_NAME,
        )
    if mix_cap < hmin:
        raise InvalidArgument(
            "mix cap",
            str(mix_cap),
            [f">= hmin ({hmin:g} mm): thinner layers cannot be printed"],
            command=CMD_NAME,
        )
    if not 0 < hmin_fraction < 1:
        raise InvalidArgument(
            "hmin fraction",
            str(hmin_fraction),
            ["a share of the height, 0 < f < 1"],
            command=CMD_NAME,
        )


def _land_on_top(
    zs: Floats, hs: Floats, height: float, first: float, hmin: float
) -> tuple[Floats, Floats, Floats]:
    """Orca overshoots / undershoots the top by up to h / 2: try uniform scalings of the last `TAIL_MM` of the
    profile (never below hmin) and keep the one whose stack ends closest to the top. Returns (z, h, tops) of the
    profile rounded to 1e-4 mm and simulated as rounded, so the text and the tops agree."""
    best: tuple[float, Floats, Floats, Floats] | None = None
    ramp = np.clip((zs - (height - TAIL_MM)) / TAIL_MM, 0.0, 1.0)
    for scale in np.linspace(1.0, 0.75, 26):
        tail = np.maximum(hs * (1.0 - (1.0 - scale) * ramp), hmin)
        zz, hh = _compress(zs, np.round(tail, 4), 0.0002)
        tops = simulate_layers(zz, hh, height, first, hmin)
        err = abs(float(tops[-1]) - height)
        if best is None or err < best[0] - 1e-9:
            best = (err, zz, hh, tops)
    assert best is not None
    return best[1], best[2], best[3]


def plan_layers(
    mesh: trimesh.Trimesh,
    *,
    hmin: float = 0.08,
    hmax: float = 0.32,
    first: float = 0.2,
    hmin_fraction: float = 0.03,
    s_thin: float = 0.85,
    r0: float = 0.30,
    slope: float = 0.20,
    mix_zranges: Sequence[tuple[float, float]] = (),
    mix_cap: float = 0.12,
    mix_margin: float = 0.5,
    object_id: int = 1,
) -> LayerPlan:
    """Adaptive layer-height profile of `mesh` (print frame).

    `hmin_fraction`: about this share of the sloped part height may reach `hmin` (the `s_thin` floor 0.85 means
    surfaces within 32 deg of horizontal; a model without such domes never gets hmin). `r0`: walls steeper than
    where the severity is <= r0 * s_thin take `hmax`. `slope`: layer height changes by at most this many mm per
    mm of z (Lipschitz). `mix_zranges` (see `mix_zranges_from`): layers there are capped at `mix_cap`; ranges
    are widened by `mix_margin` so the layer straddling a boundary is capped too. A mix range that starts on the
    bed lowers the first layer to `mix_cap` (`first_height`, to be written as `initial_layer_print_height`).

    FAIL: a layer over a mix range exceeds the cap. WARN: the stack misses the top by more than half of `hmin`."""
    _check_params(hmin, hmax, first, slope, mix_cap, hmin_fraction)
    if len(mesh.faces) == 0:
        raise InvalidArgument(
            "model",
            "no triangles",
            ["a mesh with at least one triangle"],
            command=CMD_NAME,
        )
    sev = _severity(mesh)
    if sev.height <= 0:
        raise InvalidArgument(
            "model", "zero height", ["a mesh with a vertical extent"], command=CMD_NAME
        )
    ranges = tuple((float(lo), float(hi)) for lo, hi in mix_zranges)
    s_pos = sev.s[sev.s > 0]
    s_cut = float(np.quantile(s_pos, 1.0 - hmin_fraction)) if len(s_pos) else s_thin
    thin = min(max(s_thin, s_cut), 0.995)
    # linear in severity between r0 * thin (-> hmax) and thin (-> hmin); the cusp h * s stays <= ~0.13 mm in between
    h_req = hmin + (hmax - hmin) * np.clip((1.0 - sev.s / thin) / (1.0 - r0), 0.0, 1.0)
    for lo, hi in ranges:
        in_zone = (sev.z >= lo - mix_margin) & (sev.z <= hi + mix_margin)
        h_req = np.where(in_zone, np.minimum(h_req, mix_cap), h_req)
    h_s = np.clip(_lipschitz(h_req, slope, SLAB_MM), hmin, hmax)
    height = round(sev.height, 4)
    centres = sev.z[sev.z < height - 1e-6]
    zs = np.round(np.concatenate([[0.0], centres, [height]]), 4)
    hs = np.concatenate(
        [[h_s[0]], h_s[: len(centres)], [h_s[len(centres) - 1 if len(centres) else 0]]]
    )
    first_height = first
    if any(lo < first for lo, _ in ranges):
        first_height = max(min(first, mix_cap), hmin)
    zz, hh, tops = _land_on_top(zs, hs, height, first_height, hmin)
    profile = tuple((float(z), float(h)) for z, h in zip(zz, hh, strict=True))
    heights = tuple(float(x) for x in np.diff(np.concatenate([[0.0], tops])))
    z_tops = tuple(float(t) for t in tops)
    stats = _stats(np.array(heights), hmin, hmax, slope)
    plan = LayerPlan(
        "PASS",
        (),
        heights,
        z_tops,
        profile,
        profile_text_of(profile, object_id),
        sev.height,
        first_height,
        hmin,
        hmax,
        slope,
        mix_cap,
        ranges,
        stats,
    )
    reasons = plan_problems(plan)
    verdict: Verdict = "PASS"
    if reasons:
        verdict = (
            "FAIL"
            if any(r.startswith("layer over a mix range") for r in reasons)
            else "WARN"
        )
    plan.verdict, plan.reasons = verdict, tuple(reasons)
    return plan


def _stats(heights: Floats, hmin: float, hmax: float, slope: float) -> dict[str, Any]:
    th = (
        heights[1:] if len(heights) > 1 else heights
    )  # layer 0 is the fixed first layer
    fine = th <= hmin + 0.005
    cuts = sorted(c for c in (hmin + 0.005, 0.12, 0.20, 0.25) if hmin < c < hmax)
    bounds = [hmin, *cuts, hmax]
    bands: dict[str, int] = {}
    for i, (a, b) in enumerate(zip(bounds, bounds[1:], strict=False)):
        last = i == len(bounds) - 2  # the top band includes hmax itself
        in_band = (th >= a - 1e-9) & (th <= b + 1e-6 if last else th < b - 1e-9)
        bands[f"{a:.3f}-{b:.3f}"] = int(in_band.sum())
    ratio = (
        np.abs(np.diff(th)) / np.maximum(th[:-1], 1e-9) if len(th) > 1 else np.zeros(1)
    )
    return {
        "layers": int(len(heights)),
        "min": float(th.min()),
        "max": float(th.max()),
        "median": float(np.median(th)),
        "at_hmin": int(fine.sum()),
        "at_hmin_pct": round(100.0 * float(fine.sum()) / len(th), 2),
        "height_at_hmin_pct": round(100.0 * float(th[fine].sum()) / float(th.sum()), 2),
        "bands": bands,
        "max_step_ratio": round(float(ratio.max()), 4),
        "slope_limit": slope,
    }


def plan_problems(plan: LayerPlan) -> list[str]:
    """Defects of a plan: a layer over a mix range above the cap, a stack missing the top, a profile Orca drops."""
    out: list[str] = []
    for lo, hi in plan.mix_zranges:
        over = [
            h for h in plan.heights_between(lo, hi) if h > plan.mix_cap + CAP_SLACK_MM
        ]
        if over:
            out.append(
                f"layer over a mix range {lo:.2f}-{hi:.2f} mm is {max(over):.3f} mm, above the {plan.mix_cap:g} mm cap"
            )
    if abs(plan.top_error) > TOP_WARN_FRACTION * plan.hmin:
        out.append(f"the layer stack ends {plan.top_error:+.3f} mm from the object top")
    if abs(plan.profile[-1][0] - plan.height_mm) > 1e-3:
        out.append(
            "profile top differs from the object height by more than 1e-3 mm: Orca would drop the profile"
        )
    return out


def heights_by_part(
    plan: LayerPlan, parts: Sequence[Part]
) -> Mapping[str, tuple[float, ...]]:
    """Layers printed over each part (by name): the `layer_heights` argument of `prep.regions.check_mixes`."""
